//! Проверка гипотезы: директива препроцессора внутри тела цикла ломает разбор.
use gyrfalcon_parser::bsl;

fn show(name: &str, src: &str) {
    match bsl::check_syntax(src) {
        Ok(e) if e.is_empty() => println!("[ ok ] {name}"),
        Ok(e) => println!("[ОШИБ] {name}: {} — {}", e.len(), e[0].message),
        Err(e) => println!("[СБОЙ] {name}: {e}"),
    }
}

fn main() {
    show(
        "цикл без директив",
        "Процедура П()\n\tДля Каждого С Из Т Цикл\n\t\tА = 1;\n\tКонецЦикла;\nКонецПроцедуры\n",
    );
    show("#КонецОбласти внутри цикла", "Процедура П()\n\tДля Каждого С Из Т Цикл\n\t\tА = 1;\n#КонецОбласти\n#Область Д\n\tКонецЦикла;\nКонецПроцедуры\n");
    show("#Если внутри цикла", "Процедура П()\n\tДля Каждого С Из Т Цикл\n#Если ВебКлиент Тогда\n\t\tА = 1;\n#КонецЕсли\n\tКонецЦикла;\nКонецПроцедуры\n");
    show(
        "#Область между процедурами",
        "#Область А\nПроцедура П()\nКонецПроцедуры\n#КонецОбласти\n",
    );
    show(
        "#Если внутри процедуры (не в цикле)",
        "Процедура П()\n#Если ВебКлиент Тогда\n\tА = 1;\n#КонецЕсли\nКонецПроцедуры\n",
    );
    // Второй дефект: директива посреди ВЫРАЖЕНИЯ, а не между операторами.
    show("#Если внутри выражения", "Процедура П()\n\tА = Б\n#Если ВебКлиент Тогда\n\t\t+ В\n#Иначе\n\t\t+ Г\n#КонецЕсли\n\t\t+ Д;\nКонецПроцедуры\n");
}
