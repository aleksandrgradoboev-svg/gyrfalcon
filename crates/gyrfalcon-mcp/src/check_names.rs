//! Проверка ИМЁН в модуле по индексу конфигурации — то, чего AST не видит.
//!
//! # Что здесь проверяется
//!
//! Три класса ошибок, каждый из которых проходит `check_bsl` целиком и умирает
//! только в базе:
//!
//! 1. **выдуманный метод** — имя, которого в конфигурации нет («три фантома
//!    за одну задачу», прецедент 03.09.2026);
//! 2. **число аргументов** — метод есть, зовут не с тем количеством;
//! 3. **чужой реквизит** — `РучнаяКорректировка` есть у типовых документов и
//!    отсутствует у собственного документа расширения. Зелёный
//!    `ibcmd config check`, а модуль не собирается.
//!
//! # Почему проверяются НЕ ВСЕ вызовы
//!
//! Замер 05.09.2026 на Документообороте, 187 234 вызова заведомо ПРАВИЛЬНОГО
//! кода конфигурации:
//!
//! | что сверяем | ложных тревог |
//! |---|---|
//! | все имена подряд | 88 880 = **47,5%** |
//! | только квалифицированные известным модулем | 262 = **0,73%** |
//!
//! Причина разрыва видна в хвосте частот первого варианта: `НСтр` (11 596),
//! `ЗначениеЗаполнено` (10 230), `ТипЗнч`, `СтрШаблон`, `ОткрытьФорму` —
//! встроенные функции платформы; `Вставить` (14 308), `Найти`, `Следующий`,
//! `ПолучитьОбъект` — методы её типов (Структура, Массив, Выборка). Ни того,
//! ни другого в индексе КОНФИГУРАЦИИ нет и быть не может.
//!
//! Отсюда правило, ради которого всё и написано: **проверяем только то, про
//! что индекс вправе иметь мнение.** Инструмент, врущий в половине случаев,
//! хуже отсутствующего — его перестают читать вместе с той половиной, где он
//! прав. Поэтому голый вызов здесь не «не найден», а «не проверялся», и это
//! разные слова в ответе.

use gyrfalcon_parser::module;
use rusqlite::Connection;
use serde_json::{json, Value};
use std::collections::{HashMap, HashSet};

/// Сколько замечаний показывать по умолчанию.
const DEFAULT_LIMIT: usize = 20;
const MAX_LIMIT: usize = 200;

/// Сколько похожих имён предлагать взамен ненайденного.
///
/// Подсказка обязательна, а не украшение: замер по языку запросов (31.08.2026)
/// показал, что на внятный отказ с позицией модель отвечает ПОВТОРЕНИЕМ той же
/// ошибки — шесть раз подряд. Выбор из готового списка она делает уверенно,
/// сочинение замены — нет.
const SUGGEST: usize = 3;

/// Проверить имена, встреченные в модуле, по индексу конфигурации.
pub fn check_names(conn: &Connection, args: &Value) -> Result<Value, String> {
    let source = args
        .get("source")
        .and_then(Value::as_str)
        .ok_or("нужен параметр source — текст модуля BSL")?;
    let limit = args
        .get("limit")
        .and_then(Value::as_u64)
        .map(|n| (n as usize).clamp(1, MAX_LIMIT))
        .unwrap_or(DEFAULT_LIMIT);

    let parsed = module::parse(source).map_err(|e| format!("разбор не состоялся: {e}"))?;

    // Имена модулей конфигурации: только они дают право судить о вызове.
    let модули = проверяемые_объекты(conn)?;
    // Имена, объявленные в самом тексте: переменные, параметры, счётчики.
    // Без них `Контрагенты.Количество()` по локальному массиву читается как
    // обращение к справочнику — замер 05.09.2026 дал 1,14% ложных тревог,
    // и ВСЕ до единой были именно такими.
    let предопр = предопределённые(conn)?;
    let локальные: HashSet<String> = parsed
        .locals
        .iter()
        .map(|s| s.to_lowercase())
        .collect();
    // Методы, объявленные в самом проверяемом тексте: они законны и в индексе
    // отсутствуют — модуль ещё не записан и не проиндексирован.
    let свои: HashSet<String> = parsed
        .methods
        .iter()
        .map(|m| m.name.to_lowercase())
        .collect();

    let mut кэш: HashMap<String, HashMap<String, String>> = HashMap::new();
    let mut замечания = Vec::new();
    let mut проверено = 0usize;
    let mut пропущено = 0usize;

    for call in &parsed.calls {
        let Some((qual, name)) = call.name.rsplit_once('.') else {
            // Без квалификатора — платформа или свой метод. Не наше дело.
            пропущено += 1;
            continue;
        };
        let низ = qual.to_lowercase();
        if локальные.contains(&низ) || предопр.contains(&низ) || !модули.contains(&низ) {
            // Либо это локальное имя (переменная, параметр, счётчик цикла),
            // либо квалификатор вовсе не объект конфигурации. В обоих случаях
            // индекс про него ничего не знает, и «не найдено» было бы ложью.
            пропущено += 1;
            continue;
        }
        проверено += 1;
        if свои.contains(&name.to_lowercase()) {
            continue;
        }

        // Кэш на объект: у модуля десятки вызовов к одному и тому же
        // общему модулю, и спрашивать индекс о каждом — то же самое, что
        // перечитывать словарь на каждое слово.
        if !кэш.contains_key(&низ) {
            кэш.insert(низ.clone(), методы_объекта(conn, qual)?);
        }
        let имена = &кэш[&низ];

        match имена.get(&name.to_lowercase()) {
            None => {
                замечания.push(json!({
                    "line": call.line,
                    "kind": "method_not_found",
                    "call": call.name,
                    "message": format!("метод «{name}» не найден в модуле «{qual}»"),
                    "suggest": похожие(имена, name),
                }));
            }
            Some(params) => {
                if let Some((мин, макс)) = границы_аргументов(params) {
                    let n = call.arg_count;
                    if n < мин || n > макс {
                        замечания.push(json!({
                            "line": call.line,
                            "kind": "arg_count",
                            "call": call.name,
                            "message": format!(
                                "передано аргументов: {n}, объявлено: {}{}",
                                if мин == макс { мин.to_string() } else { format!("{мин}..{макс}") },
                                if мин == макс { "" } else { " (часть со значением по умолчанию)" }
                            ),
                            "signature": params,
                        }));
                    }
                }
            }
        }
    }

    let всего = замечания.len();
    замечания.truncate(limit);

    let mut out = json!({
        "ok": всего == 0,
        "issues": замечания,
        "total": всего,
        "checked_calls": проверено,
        "skipped_calls": пропущено,
        "checked": "names_by_index",
    });
    if всего > замечания.len() {
        out["truncated"] = json!(всего - замечания.len());
    }
    // Оговорка в каждом ответе: молчание инструмента не должно читаться как
    // «имена верны». Он молчит и там, где не имел права судить.
    out["note"] = json!(format!(
        "Проверены только вызовы вида «Модуль.Метод», где Модуль — объект этой конфигурации: \
         {проверено} шт. Пропущено {пропущено} — встроенные функции платформы, методы её типов \
         и обращения через переменные: индекс о них не знает, и «не найдено» про них было бы \
         ложью. Структура кода проверяется отдельно (check_bsl), текст запроса — в канале данных."
    ));
    Ok(out)
}

/// Объекты конфигурации, у которых есть модули.
///
/// Фильтр «только с экспортными методами» пробован и отвергнут замером
/// 05.09.2026: точность вырос­ла всего с 1,25% до 1,12%, а скорость упала
/// вчетверо (GROUP BY по 103 тысячам методов). Настоящая причина остатка
/// оказалась другой — см. [`предопределённые`].
fn проверяемые_объекты(conn: &Connection) -> Result<HashSet<String>, String> {
    let mut st = conn
        .prepare("SELECT DISTINCT object_name FROM modules WHERE object_name <> ''")
        .map_err(|e| e.to_string())?;
    let rows = st
        .query_map([], |r| r.get::<_, String>(0))
        .map_err(|e| e.to_string())?;
    let mut out = HashSet::new();
    for r in rows {
        out.insert(r.map_err(|e| e.to_string())?.to_lowercase());
    }
    Ok(out)
}

/// Имена предопределённых элементов справочников, планов видов и перечислений.
///
/// Ловят класс ложных тревог, который не снимается ни локальными именами, ни
/// фильтром по модулям. Пример из корпуса (Документооборот,
/// `Catalogs/АдреснаяКнига/Ext/ManagerModule.bsl:919`):
///
/// ```text
/// РазделАдреснойКниги = Организации.ПолучитьОбъект();
/// ```
///
/// `Организации` здесь — ПРЕДОПРЕДЕЛЁННЫЙ ЭЛЕМЕНТ справочника, а
/// `ПолучитьОбъект` — метод платформы у ссылки. Но в конфигурации есть и
/// справочник `Организации` с собственным модулем, поэтому квалификатор
/// проходил фильтр, а метод в модуле, конечно, не находился.
fn предопределённые(conn: &Connection) -> Result<HashSet<String>, String> {
    let mut st = conn
        .prepare("SELECT DISTINCT item_name FROM predefined_items WHERE item_name <> ''")
        .map_err(|e| e.to_string())?;
    let rows = st
        .query_map([], |r| r.get::<_, String>(0))
        .map_err(|e| e.to_string())?;
    let mut out = HashSet::new();
    for r in rows {
        out.insert(r.map_err(|e| e.to_string())?.to_lowercase());
    }
    Ok(out)
}

/// Все методы названного объекта: имя -> сигнатура.
///
/// ОДИН запрос на объект вместо запроса на каждый вызов. Так было не сразу:
/// первая версия спрашивала индекс дважды за промах (существование + похожие),
/// и живой прогон дал **1 модуль в секунду** — при 477 у `check_bsl`. Разница
/// не в SQLite, а в числе обращений: у модуля с сотней вызовов их было двести.
fn методы_объекта(conn: &Connection, qual: &str) -> Result<HashMap<String, String>, String> {
    let mut st = conn
        .prepare(
            // COLLATE NOCASE, а не LOWER(): к результату функции SQLite не
            // применяет индекс, и idx_mod_object простаивал. Замер 05.09.2026:
            // 8 модулей/с против 1 до кэша и 60+ после этой правки.
            "SELECT m.name, m.params FROM methods m
             JOIN modules mo ON mo.id = m.module_id
             WHERE mo.object_name = ?1 COLLATE NOCASE",
        )
        .map_err(|e| e.to_string())?;
    let rows = st
        .query_map([qual], |r| {
            Ok((r.get::<_, String>(0)?, r.get::<_, String>(1).unwrap_or_default()))
        })
        .map_err(|e| e.to_string())?;
    let mut out = HashMap::new();
    for r in rows {
        let (имя, params) = r.map_err(|e| e.to_string())?;
        out.insert(имя.to_lowercase(), params);
    }
    Ok(out)
}

/// Похожие имена — подсказка вместо голого отказа.
///
/// Схожесть считается по общему префиксу и вхождению подстроки, а не полным
/// расстоянием Левенштейна: у выдуманных имён 1С промах обычно в хвосте
/// («ПересчитатьСуммыДокумента» вместо «ПересчитатьИтогиДокумента»), и дешёвый
/// признак ловит ровно этот случай.
///
/// Подсказка обязательна, а не украшение: замер по языку запросов (31.08.2026)
/// показал, что на внятный отказ с позицией модель отвечает ПОВТОРЕНИЕМ той же
/// ошибки — шесть раз подряд. Выбор из готового списка она делает уверенно,
/// сочинение замены — нет.
fn похожие(имена: &HashMap<String, String>, name: &str) -> Vec<String> {
    let искомое = name.to_lowercase();
    let mut кандидаты: Vec<(usize, &String)> = Vec::new();
    for низ in имена.keys() {
        let общий = низ
            .chars()
            .zip(искомое.chars())
            .take_while(|(a, b)| a == b)
            .count();
        let вес = if низ.contains(&искомое) || искомое.contains(низ.as_str()) {
            общий + 100
        } else {
            общий
        };
        // Меньше четырёх общих букв — это не подсказка, а шум.
        if вес >= 4 {
            кандидаты.push((вес, низ));
        }
    }
    кандидаты.sort_by_key(|(вес, _)| std::cmp::Reverse(*вес));
    кандидаты
        .into_iter()
        .take(SUGGEST)
        .map(|(_, имя)| имя.clone())
        .collect()
}

/// Сколько аргументов допускает сигнатура: (минимум, максимум).
///
/// `params` лежит в индексе строкой ровно как в объявлении:
/// `(Задача, КэшДанных = Неопределено)`. Параметры со значением по умолчанию
/// необязательны — отсюда диапазон, а не число. `None` — сигнатуру разобрать
/// не удалось, и тогда проверка молчит: выдумывать границы хуже, чем не
/// проверять.
fn границы_аргументов(params: &str) -> Option<(usize, usize)> {
    let s = params.trim();
    let s = s.strip_prefix('(')?.strip_suffix(')')?;
    if s.trim().is_empty() {
        return Some((0, 0));
    }
    let части: Vec<&str> = разбить_верхнего_уровня(s);
    let максимум = части.len();
    let минимум = части.iter().filter(|p| !p.contains('=')).count();
    Some((минимум, максимум))
}

/// Разбить список параметров по запятым верхнего уровня.
///
/// Значением по умолчанию бывает конструктор или литерал с запятой внутри —
/// `Новый Структура("А, Б")`, — поэтому наивный `split(',')` даёт лишние
/// параметры и ложное «передано меньше, чем объявлено».
fn разбить_верхнего_уровня(s: &str) -> Vec<&str> {
    let mut out = Vec::new();
    let mut depth = 0i32;
    let mut in_str = false;
    let mut start = 0usize;
    for (i, ch) in s.char_indices() {
        match ch {
            '"' => in_str = !in_str,
            _ if in_str => {}
            '(' | '[' => depth += 1,
            ')' | ']' => depth -= 1,
            ',' if depth == 0 => {
                out.push(&s[start..i]);
                start = i + ch.len_utf8();
            }
            _ => {}
        }
    }
    out.push(&s[start..]);
    out
}

/// Схема параметров для `tools/list`.
pub fn schema() -> Value {
    json!({
        "type": "object",
        "properties": {
            "source": {
                "type": "string",
                "description": "Текст модуля BSL целиком — тот, который собираешься записать"
            },
            "project": {
                "oneOf": [{"type": "string"}, {"type": "array", "items": {"type": "string"}}],
                "description":
                "Конфигурация 1С, по которой сверять имена. Обязателен, когда сервер \
                 обслуживает несколько (см. list_projects)"
            },
            "limit": {
                "type": "integer",
                "default": DEFAULT_LIMIT,
                "description": "Сколько замечаний показать; остальные посчитаны в truncated"
            }
        },
        "required": ["source"]
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn границы_без_параметров() {
        assert_eq!(границы_аргументов("()"), Some((0, 0)));
    }

    #[test]
    fn границы_обязательных() {
        assert_eq!(границы_аргументов("(А, Б)"), Some((2, 2)));
    }

    #[test]
    fn границы_с_умолчанием() {
        // Один обязательный, один со значением — законны и один, и два.
        assert_eq!(
            границы_аргументов("(Задача, КэшДанных = Неопределено)"),
            Some((1, 2))
        );
    }

    #[test]
    fn запятая_в_умолчании_не_плодит_параметры() {
        // Ровно тот случай, на котором ломается split(','): значение по
        // умолчанию содержит запятую внутри строки.
        assert_eq!(
            границы_аргументов("(Объект, Настройки = Новый Структура(\"А, Б\"))"),
            Some((1, 2))
        );
    }

    #[test]
    fn неразобранная_сигнатура_молчит() {
        // Выдумывать границы хуже, чем не проверять.
        assert_eq!(границы_аргументов("мусор"), None);
    }
}
