/// Имя MCP-сервера для уровня. У умолчания суффикса нет.
///
/// Профиль задаётся аргументом запуска, поэтому у каждого уровня свой сервер:
/// иначе урезание набора держалось бы на тексте роли, а не на механизме.
pub fn имя_сервера(t: Tier) -> String {
    match t {
        Tier::Verify => "gyrfalcon".to_string(),
        _ => format!("gyrfalcon-{}", t.profile()),
    }
}

/// Собрать тело агента под харнес.
///
/// Руководство (`agents.md`) вкладывается в КАЖДУЮ роль намеренно: скилл
/// может не подгрузиться, а тело роли лежит в контексте всегда. Дублирование
/// здесь дешевле, чем роль, работающая без правил.
pub fn роль(h: Harness, t: Tier) -> String {
    let сервер = имя_сервера(t);
    let инстр: Vec<String> = t
        .инструменты()
        .iter()
        .map(|i| format!("mcp__{сервер}__{i}"))
        .collect();
    match h {
        // У Codex read-only держится песочницей харнеса, а не текстом роли.
        Harness::Codex => format!(
            "name = \"{}\"\n\
             description = \"{}\"\n\
             sandbox_mode = \"read-only\"\n\
             developer_instructions = \"\"\"\n{}\"\"\"\n",
            t.agent_name(),
            t.описание().replace('"', "'"),
            AGENTS
        ),
        _ => {
            let список = инстр
                .iter()
                .map(|i| format!("  - {i}\n"))
                .collect::<String>();
            format!(
                "---\n\
                 name: {}\n\
                 description: \"{}\"\n\
                 tools:\n  - Read\n{}\
                 mcpServers: [{}]\n\
                 permissionMode: plan\n\
                 skills: [gyrfalcon]\n\
                 ---\n\n{}",
                t.agent_name(),
                t.описание(),
                список,
                сервер,
                AGENTS
            )
        }
    }
}

/// Харнес, в который умеем ставить.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Harness {
    ClaudeCode,
    Kilo,
    Codex,
}

impl Harness {
    pub fn parse(s: &str) -> Option<Self> {
        match s.to_lowercase().as_str() {
            "claude" | "claude-code" => Some(Harness::ClaudeCode),
            "kilo" => Some(Harness::Kilo),
            "codex" => Some(Harness::Codex),
            _ => None,
        }
    }

    pub fn name(self) -> &'static str {
        match self {
            Harness::ClaudeCode => "Claude Code",
            Harness::Kilo => "Kilo",
            Harness::Codex => "Codex",
        }
    }

    pub const ALL: &'static [Harness] = &[Harness::ClaudeCode, Harness::Kilo, Harness::Codex];
}

/// Домашний каталог пользователя.
fn home() -> Option<PathBuf> {
    std::env::var_os("USERPROFILE")
        .or_else(|| std::env::var_os("HOME"))
        .map(PathBuf::from)
}

/// Куда ложится скилл и где лежит конфиг MCP.
///
/// Каталоги берутся из переменных окружения там, где харнес их объявляет
/// (`CODEX_HOME`), иначе — из умолчания. Жёстко зашитых путей машины нет.
pub struct Places {
    pub skill: PathBuf,
    pub mcp_config: PathBuf,
    /// Каталог, куда ложатся файлы ролей.
    pub agents: PathBuf,
    /// Каталог обёрток хуков.
    pub hooks: PathBuf,
    /// Расширение файла роли: у Codex роли описываются TOML.
    pub agent_ext: &'static str,
}

pub fn places(h: Harness) -> Option<Places> {
    let home = home()?;
    Some(match h {
        Harness::ClaudeCode => Places {
            skill: home.join(".claude/skills/gyrfalcon/SKILL.md"),
            mcp_config: home.join(".claude.json"),
            agents: home.join(".claude/agents"),
            hooks: home.join(".claude/hooks"),
            agent_ext: "md",
        },
        Harness::Kilo => Places {
            // Каталог ролей у Kilo — в ЕДИНСТВЕННОМ числе (`.kilo/agent`).
            // Форма во множественном существует как legacy и молча
            // затеняется: файл туда положить можно, работать он не будет.
            skill: home.join(".kilo/skills/gyrfalcon/SKILL.md"),
            mcp_config: home.join(".kilo/mcp.json"),
            agents: home.join(".kilo/agent"),
            hooks: home.join(".kilo/plugins"),
            agent_ext: "md",
        },
        Harness::Codex => {
            let root = std::env::var_os("CODEX_HOME")
                .map(PathBuf::from)
                .unwrap_or_else(|| home.join(".codex"));
            Places {
                skill: root.join("skills/gyrfalcon/SKILL.md"),
                mcp_config: root.join("config.toml"),
                agents: root.join("agents"),
                hooks: root.join("hooks"),
                agent_ext: "toml",
            }
        }
    })
}

/// Что установщик сделал (или сделал бы в режиме плана).
#[derive(Debug)]
pub struct Действие {
    pub харнес: &'static str,
    pub что: &'static str,
    pub куда: PathBuf,
    pub итог: String,
}

/// Разложить скилл (и показать, куда пошла бы запись MCP).
///
/// `plan = true` — ничего не пишет, только перечисляет. Режим существует
/// потому, что установщик трогает чужие конфиги: показать намерение до
/// записи дешевле, чем разбирать последствия после.
pub fn install(harnesses: &[Harness], plan: bool, force: bool) -> Vec<Действие> {
    let mut out = Vec::new();
    for &h in harnesses {
        let Some(p) = places(h) else {
            out.push(Действие {
                харнес: h.name(),
                что: "skill",
                куда: PathBuf::new(),
                итог: "не найден домашний каталог (USERPROFILE/HOME)".into(),
            });
            continue;
        };

        let итог = if plan {
            "план: будет записан".to_string()
        } else {
            match записать(&p.skill, SKILL, force) {
                Ok(s) => s,
                Err(e) => format!("ОШИБКА: {e}"),
            }
        };
        out.push(Действие {
            харнес: h.name(),
            что: "skill",
            куда: p.skill,
            итог,
        });

        // Три роли: различаются правом на утверждение, привязаны к профилям
        // сервера. Ставятся файлами, потому что харнес читает их сам.
        for t in Tier::ALL {
            let путь = p.agents.join(format!("{}.{}", t.agent_name(), p.agent_ext));
            let итог = if plan {
                "план: будет записан".to_string()
            } else {
                match записать(&путь, &роль(h, *t), force) {
                    Ok(s) => s,
                    Err(e) => format!("ОШИБКА: {e}"),
                }
            };
            out.push(Действие {
                харнес: h.name(),
                что: "agent",
                куда: путь,
                итог,
            });
        }

        // Хуки-подсказки. НИКОГДА не блокируют вызов (см. модуль hooks):
        // молчаливый exit 0 при любой неудаче.
        let бинарь = std::env::current_exe()
            .map(|p| p.display().to_string())
            .unwrap_or_else(|_| "gyrfalcon".into());
        for e in crate::hooks::Event::ALL {
            let путь = crate::hooks::script_path(&p.hooks, *e);
            let тело = if cfg!(windows) {
                crate::hooks::script_cmd(&бинарь, *e)
            } else {
                crate::hooks::script_sh(&бинарь, *e)
            };
            let итог = if plan {
                "план: будет записан".to_string()
            } else {
                match записать(&путь, &тело, force) {
                    Ok(s) => s,
                    Err(e) => format!("ОШИБКА: {e}"),
                }
            };
            out.push(Действие {
                харнес: h.name(),
                что: "hook",
                куда: путь,
                итог,
            });
        }

        // Запись MCP-сервера в чужой конфиг не делается молча: у каждого
        // харнеса свой формат (JSON у одних, TOML у Codex), и порча живого
        // конфига дороже, чем строка, которую человек впишет сам. Регистрация
        // самих хуков в конфиге — там же: она правит тот же файл.
        out.push(Действие {
            харнес: h.name(),
            что: "mcp",
            куда: p.mcp_config,
            итог: "правится вручную — см. напечатанный фрагмент".into(),
        });
    }
    out
}

/// Записать файл, не затирая правленный человеком.
///
/// Приём взят у образца: если содержимое отличается от нашего — это чужая
/// правка, и молча её терять нельзя. Перезапись только по `--force`.
fn записать(куда: &Path, что: &str, force: bool) -> std::io::Result<String> {
    if куда.exists() && !force {
        let текущий = std::fs::read_to_string(куда).unwrap_or_default();
        if текущий == что {
            return Ok("уже актуален".into());
        }
        return Ok("есть и отличается (правлен?) — перезаписать: --force".into());
    }
    if let Some(dir) = куда.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(куда, что)?;
    Ok(format!("записан, {} байт", что.len()))
}

/// Фрагмент конфигурации MCP для харнеса — печатается, а не вписывается.
///
/// **Серверов объявляется три, а не один.** Профиль задаётся при запуске
/// (`--profile`), поэтому одна запись означала бы один набор инструментов на
/// все роли: либо `sql` есть у разведчика, либо его нет у аудитора. Отдельная
/// запись на профиль — единственный способ сделать урезание механическим,
/// а не обещанием в тексте роли.
pub fn фрагмент(h: Harness, db: &str) -> String {
    let бинарь = std::env::current_exe()
        .map(|p| p.display().to_string())
        .unwrap_or_else(|_| "gyrfalcon".into())
        .replace('\\', "/");
    let db = db.replace('\\', "/");

    match h {
        Harness::Codex => Tier::ALL
            .iter()
            .map(|t| {
                format!(
                    "[mcp_servers.{}]\ncommand = \"{}\"\nargs = [\"serve\", \"--db\", \"{}\", \
                     \"--profile\", \"{}\"]\n\n",
                    имя_сервера(*t),
                    бинарь,
                    db,
                    t.profile()
                )
            })
            .collect(),
        _ => {
            let записи: Vec<String> = Tier::ALL
                .iter()
                .map(|t| {
                    format!(
                        "    \"{}\": {{\n      \"command\": \"{}\",\n      \"args\": \
                         [\"serve\", \"--db\", \"{}\", \"--profile\", \"{}\"]\n    }}",
                        имя_сервера(*t),
                        бинарь,
                        db,
                        t.profile()
                    )
                })
                .collect();
            format!(
                "{{\n  \"mcpServers\": {{\n{}\n  }}\n}}\n",
                записи.join(",\n")
            )
        }
    }
}

/// Фрагмент регистрации хуков — тоже печатается.
///
/// Хуки цепляются к событиям харнеса, и запись эту делает человек: чужой
/// конфиг может содержать его собственные хуки на те же события, а
/// автоматическая правка их порядка — не то, что стоит делать молча.
pub fn фрагмент_хуков(h: Harness) -> String {
    let Some(p) = places(h) else {
        return String::new();
    };
    let mut out = String::from("{\n  \"hooks\": {\n");
    let строки: Vec<String> = crate::hooks::Event::ALL
        .iter()
        .map(|e| {
            let путь = crate::hooks::script_path(&p.hooks, *e)
                .display()
                .to_string()
                .replace('\\', "/");
            match e.matcher() {
                Some(m) => format!(
                    "    \"{}\": [{{\"matcher\": \"{}\", \"hooks\": [{{\"type\": \"command\", \
                     \"command\": \"{}\"}}]}}]",
                    e.hook_event(),
                    m,
                    путь
                ),
                None => format!(
                    "    \"{}\": [{{\"hooks\": [{{\"type\": \"command\", \"command\": \
                     \"{}\"}}]}}]",
                    e.hook_event(),
                    путь
                ),
            }
        })
        .collect();
    out.push_str(&строки.join(",\n"));
    out.push_str("\n  }\n}\n");
    out
}

