//! Установка: скилл, три роли и хуки-подсказки в конфигурацию харнеса.
//!
//! # Что ставится
//!
//! | Что | Зачем |
//! |---|---|
//! | **скилл** | правило, когда звать какой инструмент |
//! | **три роли** (`scout` / `verify` / `auditor`) | различаются правом на утверждение, привязаны к профилям сервера |
//! | **хуки-подсказки** | напоминание про индекс; никогда не блокируют вызов |
//!
//! Запись MCP-сервера в конфиг клиента **печатается, а не вписывается**:
//! у каждого харнеса свой формат, и порча живого конфига дороже, чем строка,
//! которую человек впишет сам.
//!
//! # Почему это вообще нужно
//!
//! Инструмент, выданный роли без правила о том, когда его звать, ролью не
//! зовётся. Наблюдение из практики: инструмент справки лежал в наборе трёх
//! агентов при нуле упоминаний в их описаниях и не был вызван ни разу.
//! Девять инструментов сервера ждёт та же судьба, если правило не приложено.
//!
//! # Роли сервера и роли контура — разные слои
//!
//! Роли отсюда знают **только навигацию по индексу**. Предметные роли (кто
//! ставит задачи, кто пишет код, кто проверяет ревью) их **вызывают**, а не
//! заменяются ими: разведка на двадцать вызовов происходит внутри субагента,
//! наверх приходит вывод, и вместе с ним — право на утверждение той роли,
//! которую звали. Разведчик не превращается в аудитора оттого, что его ответ
//! пересказали.
//!
//! # Отношение к стражу поиска по 1С в контуре
//!
//! Хук отсюда **подсказывает**, страж контура **запрещает** поиск по выгрузке.
//! Разница НЕ в цене поиска: он разорителен в обоих случаях (образец сам
//! оценивает grep в ~80 тыс. токенов против ~500 у индекса). Разница в двух
//! других вещах:
//!
//! 1. **надёжность замены.** Индекс общего назначения покрывает десятки
//!    языков и может не знать конкретный проект — запрет отрезал бы человека
//!    от работающего инструмента. Наш индекс покрывает одну платформу
//!    целиком: если он собран, замена гарантирована;
//! 2. **чей это компьютер.** Продукт ставится посторонним людям на их
//!    проекты, и запрещать им их же `grep` — наглость. Страж контура живёт
//!    там, где владелец сам решил, что запрещать.
//!
//! Сведение двух механизмов — отдельная работа (решение владельца
//! 29.08.2026: пусть пока будут оба).

