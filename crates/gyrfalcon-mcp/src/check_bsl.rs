//! Проверка синтаксиса модуля BSL — то, что агент зовёт ДО записи правки.
//!
//! # Зачем отдельный путь, а не `scan_collect`
//!
//! Движок один — [`bsl::check_syntax`] из парсера, — а потребителей два, и им
//! нужно разное. Индексатор (`scan::scan_collect`) сводит результат к одному
//! биту `has_errors`: при обходе 12 тысяч модулей строки и колонки девать
//! некуда. Агенту нужно обратное — где именно и что именно, иначе проверка
//! отвечает «плохо» и не говорит куда смотреть. Поэтому здесь свой путь, а
//! индексатор не тронут: у него своя работа.
//!
//! # Что эта проверка НЕ ловит
//!
//! Только структуру. Несуществующий метод, опечатку в имени реквизита, чужое
//! число аргументов парсер не видит по природе — это проверка по индексу, а не
//! по AST (см. комментарий к `bsl::check_syntax`). Поэтому ответ говорит об
//! этом прямо: «синтаксис чист» не равно «код верный», и молчание инструмента
//! не должно читаться как разрешение записывать.
//!
//! # Язык запросов сюда не относится
//!
//! Текст запроса проверяет канал данных (`gt-data-1c`: `query_check`,
//! `query_build`, `syntax` по справке вендора). Здесь — код модуля.
//! Границу держим намеренно: у того сервера источник правды живая база и
//! справка платформы, у нас — выгрузка и индекс.

use gyrfalcon_parser::bsl;
use serde_json::{json, Value};

/// Сколько ошибок показывать по умолчанию.
///
/// При каскаде tree-sitter выдаёт десятки узлов, из которых осмысленны первые.
/// Отдаём голову списка и счётчик остатка: длинная простыня не помогает
/// исправить, а мешает выбрать, с чего начать.
const DEFAULT_LIMIT: usize = 10;

/// Максимум, который разрешено запросить: выше — не диагностика, а свалка.
const MAX_LIMIT: usize = 200;

/// Длина показываемого фрагмента строки, символов.
const FRAGMENT_CHARS: usize = 120;

/// Проверить синтаксис модуля.
///
/// Вход — `source` (текст модуля). Путь к файлу намеренно НЕ принимается:
/// главный сценарий — «проверь то, что я собираюсь записать», а он про текст,
/// которого на диске ещё нет.
pub fn check_bsl(args: &Value) -> Result<Value, String> {
    let source = args
        .get("source")
        .and_then(Value::as_str)
        .ok_or("нужен параметр source — текст модуля BSL")?;

    let limit = args
        .get("limit")
        .and_then(Value::as_u64)
        .map(|n| (n as usize).clamp(1, MAX_LIMIT))
        .unwrap_or(DEFAULT_LIMIT);

    let errors = bsl::check_syntax(source).map_err(|e| format!("разбор не состоялся: {e}"))?;

    let lines: Vec<&str> = source.lines().collect();
    let shown: Vec<Value> = errors
        .iter()
        .take(limit)
        .map(|e| {
            let mut item = json!({
                "line": e.line,
                "column": e.column,
                "message": e.message,
            });
            // Фрагмент строки: без него ответ называет координату, а модель
            // всё равно перечитывает файл, чтобы понять, о чём речь.
            if let Some(text) = lines.get(e.line as usize - 1) {
                let fragment: String = text.trim_end().chars().take(FRAGMENT_CHARS).collect();
                item["fragment"] = json!(fragment);
                // Подозрительные символы — частая причина на реальных выгрузках:
                // U+2003 и прочие юникодные пробелы 1С глотает, а глазами их
                // не видно вовсе (замер 27.08.2026, единственный сбой корпуса A).
                let odd: Vec<String> = text
                    .chars()
                    .filter(|c| !c.is_ascii() && !('А'..='я').contains(c) && *c != 'ё' && *c != 'Ё')
                    .map(|c| format!("U+{:04X}", c as u32))
                    .collect();
                if !odd.is_empty() {
                    item["suspicious_chars"] = json!(odd);
                }
            }
            item
        })
        .collect();

    let mut out = json!({
        "ok": errors.is_empty(),
        "errors": shown,
        "total": errors.len(),
        "checked": "syntax_only",
    });

    if errors.len() > shown.len() {
        out["truncated"] = json!(errors.len() - shown.len());
    }

    // Оговорка едет в КАЖДОМ ответе, а не только в описании инструмента:
    // описание модель читает один раз при загрузке, ответ — каждый раз.
    // Зелёный вердикт без неё читается как «код верный» — ровно та ошибка,
    // что уже стоила нам вечера на `ibcmd config check`.
    out["note"] = json!(
        "Проверена ТОЛЬКО структура кода. Существование методов и реквизитов, число \
         аргументов, свои против типовых имён — не проверялось: это индекс, а не AST. \
         Текст ЗАПРОСА проверяется не здесь, а в канале данных (query_check)."
    );

    Ok(out)
}

/// Схема параметров для `tools/list`.
pub fn schema() -> Value {
    json!({
        "type": "object",
        "properties": {
            "source": {
                "type": "string",
                "description": "Текст модуля BSL целиком — тот, который собираешься записать"
            },
            "limit": {
                "type": "integer",
                "default": DEFAULT_LIMIT,
                "description": "Сколько ошибок показать; остальные посчитаны в truncated"
            }
        },
        "required": ["source"]
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn проверить(src: &str) -> Value {
        check_bsl(&json!({ "source": src })).unwrap()
    }

    #[test]
    fn целый_модуль_чист() {
        let v = проверить("Процедура Тест()\n\tА = 1;\nКонецПроцедуры\n");
        assert_eq!(v["ok"], json!(true));
        assert_eq!(v["total"], json!(0));
        assert_eq!(v["errors"].as_array().unwrap().len(), 0);
    }

    #[test]
    fn незакрытая_процедура_ловится_с_координатой() {
        let v = проверить("Процедура Тест()\n\tА = 1;\n");
        assert_eq!(v["ok"], json!(false));
        assert!(v["total"].as_u64().unwrap() > 0);
        let первая = &v["errors"][0];
        assert!(первая["line"].as_u64().unwrap() >= 1, "нет строки");
        assert!(первая["message"].is_string(), "нет сообщения");
    }

    #[test]
    fn фрагмент_строки_возвращается() {
        let v = проверить("Процедура Тест()\n\tА = (1 + 2));\nКонецПроцедуры\n");
        let есть_фрагмент = v["errors"]
            .as_array()
            .unwrap()
            .iter()
            .any(|e| e.get("fragment").is_some());
        assert!(есть_фрагмент, "фрагмент строки не приложен: {v}");
    }

    #[test]
    fn юникодный_пробел_отмечается() {
        // Грамматика такой пробел уже глотает (правка форка d506854), но если
        // ошибка рядом — символ надо назвать: глазами он неотличим от обычного.
        let v = проверить("Процедура\u{2003}Тест(\n\tА = 1;\n");
        let есть = v["errors"]
            .as_array()
            .unwrap()
            .iter()
            .any(|e| e.get("suspicious_chars").is_some());
        assert!(есть, "U+2003 не отмечен: {v}");
    }

    #[test]
    fn лимит_режет_и_считает_остаток() {
        // Четыре лишние скобки — четыре независимые ошибки (замер пробником:
        // незакрытые процедуры схлопываются в ОДИН ERROR-узел, а скобки нет,
        // поэтому каскад строим на них, а не на объявлениях).
        let битый =
            "Процедура Т()\n\tА = (1));\n\tБ = (2));\n\tВ = (3));\n\tГ = (4));\nКонецПроцедуры\n";
        let v = check_bsl(&json!({ "source": битый, "limit": 2 })).unwrap();
        assert_eq!(v["total"], json!(4), "ожидались 4 ошибки: {v}");
        assert_eq!(
            v["errors"].as_array().unwrap().len(),
            2,
            "лимит не сработал"
        );
        assert_eq!(v["truncated"], json!(2), "остаток посчитан неверно");
    }

    #[test]
    fn оговорка_о_неполноте_всегда_в_ответе() {
        // Даже на чистом модуле: зелёный вердикт без неё читается как
        // «код верный», а имена не проверялись вовсе.
        let v = проверить("Процедура Тест()\nКонецПроцедуры\n");
        let note = v["note"].as_str().unwrap();
        assert!(note.contains("ТОЛЬКО структура"), "оговорка потеряна");
        assert_eq!(v["checked"], json!("syntax_only"));
    }

    #[test]
    fn без_source_внятный_отказ() {
        let e = check_bsl(&json!({})).unwrap_err();
        assert!(e.contains("source"), "отказ не называет параметр: {e}");
    }

    #[test]
    fn пропуск_точки_с_запятой_не_ошибка() {
        // В BSL перевод строки разделяет операторы — парсер прав, и инструмент
        // не должен изобретать строгость, которой нет в языке.
        let v = проверить("Процедура Тест()\n\tА = 1\n\tБ = 2\nКонецПроцедуры\n");
        assert_eq!(v["ok"], json!(true), "ложная тревога на пропуске ;");
    }
}
