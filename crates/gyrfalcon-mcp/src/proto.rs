//! Протокол MCP: JSON-RPC 2.0 поверх stdio и HTTP.
//!
//! Модуль отвечает только за конверт — разбор запроса, форму ответа, коды
//! ошибок. Что именно делают инструменты, он не знает: это `tools`.
//! Каким транспортом конверт доехал, он не знает тоже: это `server`
//! (stdio) и `mcp_http` (Streamable HTTP).
//!
//! # Почему свой разбор, а не готовый крейт
//!
//! Нужны три метода (`initialize`, `tools/list`, `tools/call`) и два
//! транспорта. Зависимость ради этого стоила бы дороже, чем сто строк разбора,
//! и привязала бы версию протокола к чужому графику релизов.

use serde::{Deserialize, Serialize};
use serde_json::{json, Value};

/// Версии протокола, на которых сервер умеет говорить, — от новой к старой.
///
/// Список из трёх, а не из одной, потому что транспорты появились в разных
/// ревизиях: Streamable HTTP введён в 2025-03-26, а stdio-клиенты в контуре
/// до сих пор представляются 2024-11-05. Сервер отдаёт только инструменты —
/// того, что различает эти ревизии (elicitation, выборка, ссылки на ресурсы),
/// у него нет, и потому поддержка всех трёх здесь не обещание, а факт: между
/// ними ему нечего менять в поведении.
pub const ВЕРСИИ: [&str; 3] = ["2025-06-18", "2025-03-26", "2024-11-05"];

/// Версия, которой сервер отвечает клиенту, не назвавшему свою.
///
/// Самая старая из поддержанных, а не самая новая: молчание клиента о версии
/// значит, что он старый, и предлагать ему то, чего он не знает, — верный
/// способ получить разрыв соединения вместо работы.
pub const PROTOCOL_VERSION: &str = ВЕРСИИ[2];

/// Выбрать версию ответа на `initialize` по версии, названной клиентом.
///
/// Знакомая — отдаётся как есть: говорить на версии собеседника дешевле, чем
/// заставлять его понижаться. Незнакомая — отдаётся самая новая наша, как
/// требует спецификация: сервер обязан назвать версию, которую поддерживает,
/// и дальше уже дело клиента — принять её или отсоединиться.
pub fn согласовать_версию(запрошенная: Option<&str>) -> &'static str {
    match запрошенная {
        None => PROTOCOL_VERSION,
        Some(v) => ВЕРСИИ
            .iter()
            .copied()
            .find(|известная| *известная == v)
            .unwrap_or(ВЕРСИИ[0]),
    }
}

/// Входящий запрос JSON-RPC.
///
/// `id` отсутствует у уведомлений (notifications) — на них ответ не шлётся.
#[derive(Debug, Deserialize)]
pub struct Request {
    #[serde(default)]
    pub id: Option<Value>,
    pub method: String,
    #[serde(default)]
    pub params: Value,
}

/// Коды ошибок JSON-RPC 2.0, которые сервер действительно возвращает.
///
/// Список короче стандартного намеренно: `InvalidRequest` (-32600) и
/// `InternalError` (-32603) сюда не входят, потому что ни один путь их не
/// отдаёт. Заведённый «на будущее» вариант перечисления — обещание, которого
/// код не выполняет: он выглядит как поддержанный случай и не является им.
/// Понадобятся — добавляются вместе с местом, которое их возвращает.
#[derive(Debug, Clone, Copy, Serialize)]
#[repr(i32)]
pub enum ErrorCode {
    ParseError = -32700,
    MethodNotFound = -32601,
    InvalidParams = -32602,
}

/// Успешный ответ на запрос с данным `id`.
pub fn ok(id: Value, result: Value) -> Value {
    json!({"jsonrpc": "2.0", "id": id, "result": result})
}

/// Ответ-ошибка уровня протокола.
///
/// Важно отличать от ошибки инструмента: неверный SQL — это результат вызова
/// с `isError: true`, а не поломка протокола. Смешивать нельзя, иначе клиент
/// не отличит «сервер сломался» от «запрос не удался».
pub fn err(id: Value, code: ErrorCode, message: impl Into<String>) -> Value {
    json!({
        "jsonrpc": "2.0",
        "id": id,
        "error": {"code": code as i32, "message": message.into()}
    })
}

/// Ответ на `initialize`: чем сервер представляется клиенту.
///
/// `protocol` — уже согласованная версия (см. `согласовать_версию`), а не
/// константа: иначе сервер отвечал бы одно и то же клиенту, который назвал
/// другое, и разошёлся бы с ним молча.
pub fn initialize_result(server_name: &str, version: &str, protocol: &str) -> Value {
    json!({
        "protocolVersion": protocol,
        "capabilities": {"tools": {"listChanged": false}},
        "serverInfo": {"name": server_name, "version": version}
    })
}

/// Результат вызова инструмента: текстовое содержимое.
///
/// `is_error = true` означает «инструмент отработал и говорит, что не вышло».
/// Это НЕ ошибка протокола — см. `err`.
pub fn tool_result(text: String, is_error: bool) -> Value {
    json!({
        "content": [{"type": "text", "text": text}],
        "isError": is_error
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn разбирает_запрос_с_параметрами() {
        let r: Request = serde_json::from_str(
            r#"{"jsonrpc":"2.0","id":1,"method":"tools/call","params":{"name":"x"}}"#,
        )
        .unwrap();
        assert_eq!(r.method, "tools/call");
        assert_eq!(r.id, Some(json!(1)));
        assert_eq!(r.params["name"], "x");
    }

    #[test]
    fn уведомление_без_id_разбирается() {
        // Уведомления (notifications) не несут id и не требуют ответа.
        let r: Request =
            serde_json::from_str(r#"{"jsonrpc":"2.0","method":"notifications/initialized"}"#)
                .unwrap();
        assert!(r.id.is_none());
    }

    #[test]
    fn ошибка_инструмента_не_ошибка_протокола() {
        // Ключевое различие: результат с isError — успешный ответ JSON-RPC.
        let res = ok(json!(1), tool_result("не вышло".into(), true));
        assert!(res.get("error").is_none(), "это не ошибка протокола");
        assert_eq!(res["result"]["isError"], true);
    }

    #[test]
    fn знакомая_версия_отдаётся_как_есть() {
        // Клиент по HTTP представляется 2025-03-26 — сервер обязан ответить
        // тем же, а не константой транспорта stdio.
        assert_eq!(согласовать_версию(Some("2025-03-26")), "2025-03-26");
        assert_eq!(согласовать_версию(Some("2024-11-05")), "2024-11-05");
    }

    #[test]
    fn незнакомая_версия_понижается_до_самой_новой_нашей() {
        assert_eq!(согласовать_версию(Some("2077-01-01")), ВЕРСИИ[0]);
        assert_eq!(согласовать_версию(Some("")), ВЕРСИИ[0]);
    }

    #[test]
    fn молчание_о_версии_читается_как_старый_клиент() {
        assert_eq!(согласовать_версию(None), "2024-11-05");
    }

    #[test]
    fn согласованная_версия_попадает_в_ответ() {
        let r = initialize_result("gyrfalcon", "0.1.2", "2025-06-18");
        assert_eq!(r["protocolVersion"], "2025-06-18");
        assert_eq!(r["serverInfo"]["name"], "gyrfalcon");
    }

    #[test]
    fn коды_ошибок_соответствуют_стандарту() {
        assert_eq!(ErrorCode::MethodNotFound as i32, -32601);
        assert_eq!(ErrorCode::InvalidParams as i32, -32602);
    }
}
