//! Отстал ли индекс от исходников — и на сколько.
//!
//! # Зачем это идёт ПЕРВЫМ в вехе 7 (решение владельца 29.08.2026)
//!
//! Из двух незакрытых работ — «сказать, что индекс отстал» и «догнать
//! инкрементом» — раньше идёт первая, потому что её дефект МОЛЧИТ.
//! Отсутствующий инкремент виден сразу: сборка долгая, это заметно.
//! Отставший индекс не виден вовсе — он отвечает уверенно и неверно,
//! и агент строит на его ответе выводы, не имея повода усомниться.
//!
//! Отсюда порядок: устаревший индекс, который об этом ГОВОРИТ, безопаснее
//! свежего, о свежести которого судить нечем. Тот же довод, по которому
//! `coverage` носит оговорку о неполноте в самом ответе, а не в документации.
//!
//! # Чем меряется отставание (решение владельца 29.08.2026)
//!
//! Двумя признаками сразу, потому что каждый по отдельности слеп:
//!
//! * **mtime файлов** против `built_at` — ловит правку в рабочей копии,
//!   то есть ровно то состояние, в котором разработчик и живёт;
//! * **git HEAD** против записанного при сборке — ловит переключение ветки
//!   и `git pull`, после которых mtime может и не измениться: git
//!   восстанавливает содержимое, а время правки ставит своё, и файл,
//!   вернувшийся к прежнему виду, выглядит нетронутым.
//!
//! Полный хэш содержимого отвергнут: он точен, но стоит чтения всего
//! корпуса (154,5 с на ЕРП.УХ) — это цена СБОРКИ, а не проверки.
//!
//! # Почему обход не читает файлы
//!
//! Проверка обязана быть дешевле ответа, который она сопровождает. Здесь
//! только `metadata()` — размер и время правки, без открытия файла. На
//! ЕРП.УХ это ~1–2 с холодным кэшом и десятки миллисекунд прогретым.
//!
//! # Чего эта проверка НЕ говорит
//!
//! «Не отстал» здесь значит «ни один файл не новее сборки и ветка та же».
//! Это НЕ значит «индекс верен»: файл мог быть изменён и возвращён обратно
//! с сохранением mtime, а индекс мог быть собран с дефектом. Отсутствие
//! записи об отставании — не гарантия, ровно как в `coverage`.

use std::path::{Path, PathBuf};
use std::time::UNIX_EPOCH;
use walkdir::WalkDir;

/// Расширения, чьё изменение делает индекс устаревшим.
///
/// Тот же набор, что читает сборка: `.bsl` (модули) и `.xml` (метаданные,
/// формы, права, состав). Файл другого расширения индекс не читает, и его
/// правка отставанием не является — иначе `stale` загорался бы от чужого
/// `.md` в каталоге выгрузки и обесценился бы за неделю.
const РАСШИРЕНИЯ: [&str; 2] = ["bsl", "xml"];

/// Сколько изменённых файлов называть поимённо.
///
/// Список нужен, чтобы отставание можно было ПРОВЕРИТЬ, а не принять на
/// веру; но полный перечень на пересобранной ветке — это тысячи путей,
/// то есть ответ дороже самого запроса. Три штуки достаточно, чтобы
/// увидеть, о каких файлах речь, и число говорит остальное.
const ПРИМЕРОВ: usize = 3;

/// Состояние индекса относительно исходников.
#[derive(Debug, Clone, Default)]
pub struct Freshness {
    /// Индекс отстал: есть изменённые файлы или разошёлся коммит.
    pub stale: bool,
    /// Сколько файлов новее сборки индекса.
    pub changed: usize,
    /// Несколько путей для проверки утверждения (относительно корня).
    pub examples: Vec<String>,
    /// Коммит, записанный при сборке (пусто — не записан или не git).
    pub built_commit: String,
    /// Коммит рабочей копии сейчас (пусто — не git или git недоступен).
    pub current_commit: String,
    /// Секунды эпохи: когда собран индекс.
    pub built_at: u64,
    /// Сколько секунд назад собран.
    pub age_secs: u64,
    /// Проверка не выполнена: каталога исходников нет на этой машине.
    ///
    /// Отдельно от `stale`, потому что это РАЗНЫЕ вещи. «Не смог проверить»
    /// нельзя показывать как «свежий» — молчание тогда значило бы два
    /// разных состояния сразу.
    pub unchecked: Option<String>,
}

impl Freshness {
    /// Строка для агента — или `None`, если говорить не о чем.
    ///
    /// Свежий индекс молчит: платить токенами за «всё хорошо» в КАЖДОМ
    /// ответе значит проиграть по критерию №2, по которому мы и так идём
    /// вровень с прежний инструментом (1,04×).
    pub fn note(&self) -> Option<String> {
        if let Some(причина) = &self.unchecked {
            return Some(format!(
                "свежесть индекса не проверена: {причина}. Ответ может не учитывать правок"
            ));
        }
        if !self.stale {
            return None;
        }
        let mut части = Vec::new();
        if self.changed > 0 {
            let примеры = if self.examples.is_empty() {
                String::new()
            } else {
                format!(" ({})", self.examples.join(", "))
            };
            части.push(format!(
                "{} {} после сборки{примеры}",
                self.changed,
                склонение(self.changed)
            ));
        }
        if !self.built_commit.is_empty()
            && !self.current_commit.is_empty()
            && self.built_commit != self.current_commit
        {
            части.push(format!(
                "коммит рабочей копии {} против {} при сборке",
                кратко(&self.current_commit),
                кратко(&self.built_commit)
            ));
        }
        Some(format!(
            "ИНДЕКС ОТСТАЛ ({}, собран {} назад). Пересоберите: gyrfalcon build <путь> --out <файл>",
            части.join("; "),
            длительность(self.age_secs)
        ))
    }
}

/// «1 файл изменён» против «5 файлов изменены».
///
/// Мелочь, но отметку читает агент, а согласование в тексте — это признак,
/// по которому сообщение отличают от заглушки. «1 файлов» выглядит
/// недоделкой, и доверие к остальному тексту падает вместе с ним.
fn склонение(n: usize) -> &'static str {
    let сотни = n % 100;
    let единицы = n % 10;
    if (11..=14).contains(&сотни) {
        return "файлов изменены";
    }
    match единицы {
        1 => "файл изменён",
        2..=4 => "файла изменены",
        _ => "файлов изменены",
    }
}

fn кратко(sha: &str) -> String {
    sha.chars().take(8).collect()
}

/// Человеческая длительность. Без локали и часового пояса: индекс
/// переносится между машинами, а «два часа назад» переносится, в отличие
/// от «13:40».
fn длительность(secs: u64) -> String {
    match secs {
        0..=90 => format!("{secs} с"),
        91..=5400 => format!("{} мин", secs / 60),
        5401..=172_800 => format!("{} ч", secs / 3600),
        _ => format!("{} дн", secs / 86_400),
    }
}

/// Проверить свежесть индекса по его собственным записям.
///
/// `built_at` и `source_path` берутся из `index_meta` — индекс сам знает,
/// откуда и когда он собран. Аргументами их не передаём: тогда вызывающий
/// мог бы сверить индекс не с тем каталогом и получить складный неверный
/// ответ.
pub fn check(built_at: u64, source: &str, built_commit: &str) -> Freshness {
    let now = std::time::SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    let mut f = Freshness {
        built_at,
        age_secs: now.saturating_sub(built_at),
        built_commit: built_commit.to_string(),
        ..Default::default()
    };

    let root = PathBuf::from(source);
    if source.is_empty() {
        f.unchecked = Some("индекс не помнит, из какого каталога собран".into());
        return f;
    }
    if !root.is_dir() {
        f.unchecked = Some(format!("каталога {source} нет на этой машине"));
        return f;
    }
    if built_at == 0 {
        f.unchecked = Some("индекс не помнит времени сборки".into());
        return f;
    }

    let (changed, examples) = изменённые(&root, built_at);
    f.changed = changed;
    f.examples = examples;

    f.current_commit = crate::git::head(&root).unwrap_or_default();
    let коммит_разошёлся = !f.built_commit.is_empty()
        && !f.current_commit.is_empty()
        && f.built_commit != f.current_commit;

    f.stale = changed > 0 || коммит_разошёлся;
    f
}

/// Обойти дерево и посчитать файлы новее сборки.
///
/// Считаем ВСЕ, а не останавливаемся на первом: число — это то, по чему
/// читающий судит о масштабе. «Один файл» и «четыре тысячи» требуют разных
/// решений, а обход всё равно уже идёт.
fn изменённые(root: &Path, built_at: u64) -> (usize, Vec<String>) {
    let mut n = 0usize;
    let mut примеры = Vec::new();
    // Запас в секунду: mtime файловой системы и часы процесса берутся из
    // разных источников, и файл, записанный за миг до конца сборки, иначе
    // выглядел бы изменённым после неё. Без запаса `stale` загорался бы
    // сразу после успешной пересборки — и правило «отставание значит
    // отставание» умерло бы на первом же ложном срабатывании.
    let порог = built_at + 1;
    for e in WalkDir::new(root)
        .into_iter()
        .filter_map(std::result::Result::ok)
        .filter(|e| e.file_type().is_file())
    {
        let подходит = e
            .path()
            .extension()
            .and_then(|x| x.to_str())
            .is_some_and(|x| РАСШИРЕНИЯ.iter().any(|r| x.eq_ignore_ascii_case(r)));
        if !подходит {
            continue;
        }
        let Ok(m) = e.metadata() else { continue };
        let Ok(t) = m.modified() else { continue };
        let Ok(d) = t.duration_since(UNIX_EPOCH) else {
            continue;
        };
        if d.as_secs() > порог {
            n += 1;
            if примеры.len() < ПРИМЕРОВ {
                let rel = e
                    .path()
                    .strip_prefix(root)
                    .unwrap_or(e.path())
                    .to_string_lossy()
                    .replace('\\', "/");
                примеры.push(rel);
            }
        }
    }
    (n, примеры)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;
    use std::path::PathBuf;

    fn сейчас() -> u64 {
        std::time::SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_secs()
    }

    /// Каталог с одним файлом. Время правки НЕ подделывается: вместо этого
    /// сдвигается точка отсчёта (`built_at`), что проверяет ровно то же
    /// сравнение и не требует зависимости ради тестов.
    struct Корпус(PathBuf);

    impl Корпус {
        fn новый(метка: &str, файл: &str) -> Self {
            let dir = std::env::temp_dir().join(format!("gyrfalcon-fresh-{метка}"));
            let _ = fs::remove_dir_all(&dir);
            let p = dir.join(файл);
            fs::create_dir_all(p.parent().unwrap()).unwrap();
            fs::write(&p, "Процедура Х() КонецПроцедуры").unwrap();
            Self(dir)
        }
        fn путь(&self) -> String {
            self.0.to_string_lossy().to_string()
        }
        /// Время правки файла — от него отсчитываются «до» и «после».
        fn mtime(&self, файл: &str) -> u64 {
            fs::metadata(self.0.join(файл))
                .unwrap()
                .modified()
                .unwrap()
                .duration_since(UNIX_EPOCH)
                .unwrap()
                .as_secs()
        }
    }

    impl Drop for Корпус {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    #[test]
    fn свежий_индекс_молчит() {
        let файл = "CommonModules/А/Ext/Module.bsl";
        let к = Корпус::новый("свежий", файл);
        // Индекс собран ПОСЛЕ правки файла.
        let f = check(к.mtime(файл) + 600, &к.путь(), "");
        assert!(!f.stale, "файл старше сборки — отставания нет");
        assert!(f.note().is_none(), "свежий индекс не платит токенами");
    }

    #[test]
    fn правка_после_сборки_видна() {
        let файл = "CommonModules/Б/Ext/Module.bsl";
        let к = Корпус::новый("правка", файл);
        // Индекс собран ДО правки файла.
        let f = check(к.mtime(файл) - 600, &к.путь(), "");
        assert!(f.stale);
        assert_eq!(f.changed, 1);
        let note = f.note().unwrap();
        assert!(note.contains("ОТСТАЛ"), "{note}");
        // Утверждение обязано быть проверяемым: путь назван.
        assert!(note.contains("Module.bsl"), "{note}");
    }

    #[test]
    fn чужое_расширение_отставанием_не_считается() {
        let к = Корпус::новый("чужое", "README.md");
        let f = check(к.mtime("README.md") - 600, &к.путь(), "");
        assert!(!f.stale, "индекс .md не читает — правка его не старит");
    }

    #[test]
    fn xml_метаданных_считается_наравне_с_bsl() {
        let файл = "Catalogs/Номенклатура.xml";
        let к = Корпус::новый("xml", файл);
        let f = check(к.mtime(файл) - 600, &к.путь(), "");
        assert!(f.stale, "метаданные меняют индекс так же, как код");
    }

    #[test]
    fn пропавший_каталог_не_выдаётся_за_свежесть() {
        // Ключевое: «не смог проверить» и «свежий» — разные состояния,
        // и молчать во втором случае можно, а в первом нельзя.
        let f = check(сейчас(), "Z:/нет/такого/каталога", "");
        assert!(!f.stale);
        assert!(f.unchecked.is_some());
        let note = f.note().expect("непроверенное обязано говорить о себе");
        assert!(note.contains("не проверена"), "{note}");
    }

    #[test]
    fn пустой_источник_тоже_непроверен() {
        let f = check(сейчас(), "", "");
        assert!(f.unchecked.is_some());
        assert!(f.note().is_some());
    }

    #[test]
    fn нулевое_время_сборки_не_выдаётся_за_свежесть() {
        let к = Корпус::новый("нулевое", "CommonModules/Д/Ext/Module.bsl");
        let f = check(0, &к.путь(), "");
        assert!(
            f.unchecked.is_some(),
            "без времени сборки сравнивать не с чем"
        );
        assert!(!f.stale);
    }

    #[test]
    fn расхождение_коммита_старит_индекс_без_единой_правки() {
        // Тот случай, ради которого git и добавлен: `git checkout` вернул
        // прежнее содержимое, mtime не выдал ничего, а конфигурация другая.
        let f = Freshness {
            stale: true,
            built_commit: "a".repeat(40),
            current_commit: "b".repeat(40),
            age_secs: 7200,
            ..Default::default()
        };
        let note = f.note().unwrap();
        assert!(note.contains("bbbbbbbb"), "{note}");
        assert!(note.contains("aaaaaaaa"), "{note}");
    }

    #[test]
    fn склонение_согласовано_с_числом() {
        assert_eq!(склонение(1), "файл изменён");
        assert_eq!(склонение(3), "файла изменены");
        assert_eq!(склонение(5), "файлов изменены");
        assert_eq!(склонение(11), "файлов изменены", "11 — не «файл»");
        assert_eq!(склонение(21), "файл изменён");
        assert_eq!(склонение(112), "файлов изменены", "112 — не «файла»");
        assert_eq!(склонение(122), "файла изменены");
    }

    #[test]
    fn длительность_читается_человеком() {
        assert_eq!(длительность(30), "30 с");
        assert_eq!(длительность(600), "10 мин");
        assert_eq!(длительность(7200), "2 ч");
        assert_eq!(длительность(300_000), "3 дн");
    }

    #[test]
    fn запас_секунды_гасит_ложную_тревогу_сразу_после_сборки() {
        // Файл записан в ту же секунду, что закончилась сборка. Без запаса
        // это читалось бы как «отстал» немедленно после успешной пересборки.
        let файл = "CommonModules/Г/Ext/Module.bsl";
        let к = Корпус::новый("запас", файл);
        let f = check(к.mtime(файл), &к.путь(), "");
        assert!(!f.stale, "своя же сборка не должна выглядеть отставанием");
    }
}
