//! Единый взвешенный балл поиска (решение Р-017).
//!
//! # Зачем модуль
//!
//! До 29.08.2026 поиск отдавал НЕСКОЛЬКО СПИСКОВ: точные совпадения по
//! `LIKE` отдельно, семантику отдельным разделом (Р-016). Устройство
//! обходило задачу ранжирования вместо того, чтобы её решать, и стоило
//! дорого: раздел `semantic` пришивался к каждому ответу и занимал
//! 79–81% выдачи — на запросе с точно известным именем тоже.
//!
//! Эталон (внешний образец) ту же задачу решает: `semantic_query` считает один балл
//! из одиннадцати сигналов. Здесь — то же устройство, начатое с четырёх.
//!
//! # Правило, из-за которого модуль устроен именно так
//!
//! Урок 10.08.2026 (память контура): ненормированный косинус шёл слагаемым
//! во взвешенную сумму, молча проигрывал сигналам с широким разбросом и дал
//! recall 10% при исправном поиске. Дефект бесшумный — формула выглядит
//! рабочей.
//!
//! Отсюда два обязательных условия, оба проверяются тестами:
//!
//! 1. **каждый сигнал нормируется по выдаче** перед сложением;
//! 2. **сырое значение остаётся рядом** (`Signals`), потому что после
//!    нормировки «лучший из мусора» неотличим от точного попадания.
//!
//! # Чего здесь нет
//!
//! Весов, подобранных замером. Корпуса запросов с прежний инструментными ответами
//! пока не существует, поэтому веса ниже — ЧЕРНОВЫЕ, и так они помечены
//! в коде. Подбор — отдельный шаг после 13-го сценария.

use std::collections::HashMap;

/// Сигналы, из которых складывается балл. Каждый — сырое значение.
///
/// Хранятся все, даже нулевые: «сигнал не сработал» и «сигнала не было»
/// должны быть различимы в выдаче, иначе разбирать плохой ответ нечем.
#[derive(Debug, Clone, Default)]
pub struct Signals {
    /// 1. Точность совпадения имени: 1.0 — полное равенство,
    ///    0.5 — начинается с запроса, 0.25 — содержит как подстроку.
    pub exact: f32,
    /// 2. BM25 из FTS5 (триграммы), уже приведённый к «больше — лучше».
    pub bm25: f32,
    /// 3. Косинус семантической близости, 0..1.
    pub semantic: f32,
    /// 4. Связность по графу вызовов: сколько рёбер у сущности.
    ///    Часто вызываемое релевантнее одиночного при прочих равных.
    pub degree: f32,
    /// 5. Совпадение с СИНОНИМОМ объекта — русским названием из метаданных.
    ///
    /// Сигнала с таким смыслом у прежнего инструмента нет и быть не может: в мире 158
    /// языков у сущности одно имя. В 1С их два — `АдреснаяКнига` и
    /// «Адресная книга», — и пользователь спрашивает вторым.
    pub synonym: f32,
    /// 6. Редкость слов запроса (IDF): запрос из редких слов, совпавший
    ///    с именем, значит больше, чем совпадение по «Получить» или «Данные».
    ///
    /// Считался при сборке (`semantic_tokens.idf`) и до 29.08.2026 в
    /// ранжировании не участвовал вовсе — лежал мёртвым грузом.
    pub idf: f32,
    /// 7. Использование в коде (`metadata_code_usages`): объект, который
    ///    реально читают и пишут, релевантнее объявленного и забытого.
    ///
    /// У прежнего инструмента ближайший родственник — graph diffusion; у нас связь
    /// метаданных с кодом прямее, потому что она в индексе явная.
    pub usage: f32,
}

/// Черновые веса (Р-017): подобраны рассуждением, НЕ замером.
///
/// Порядок величин задан смыслом, а не подгонкой: точное совпадение имени
/// должно перевешивать любой другой сигнал, иначе поиск по известному имени
/// начнёт отдавать «похожее по смыслу» вперёд точного — ровно та жалоба,
/// с которой начался Р-017.
pub const W_EXACT: f32 = 0.40;
pub const W_SYNONYM: f32 = 0.15;
pub const W_BM25: f32 = 0.15;
pub const W_SEMANTIC: f32 = 0.13;
pub const W_IDF: f32 = 0.07;
pub const W_USAGE: f32 = 0.06;
pub const W_DEGREE: f32 = 0.04;

/// Одна строка выдачи до ранжирования.
#[derive(Debug, Clone)]
pub struct Candidate {
    pub kind: String,
    pub name: String,
    pub payload: Vec<String>,
    pub signals: Signals,
}

/// Результат после ранжирования.
#[derive(Debug, Clone)]
pub struct Ranked {
    pub kind: String,
    pub name: String,
    pub payload: Vec<String>,
    /// Итоговый взвешенный балл 0..1.
    pub score: f32,
    /// Сигналы ДО нормировки — чтобы можно было объяснить место в списке.
    pub signals: Signals,
    /// Какой сигнал внёс наибольший вклад. Не украшение: без него
    /// «почему это первое» выясняется только чтением кода.
    pub reason: &'static str,
}

/// Нормировка одного сигнала по выдаче: min-max в 0..1.
///
/// Вырожденный случай (все значения равны) даёт НОЛЬ, а не единицу:
/// сигнал, одинаковый у всех кандидатов, ничего не различает, и притворяться
/// максимальным ему нельзя — иначе он молча перетянет формулу на себя.
fn нормировать(значения: &[f32]) -> Vec<f32> {
    let (mut lo, mut hi) = (f32::INFINITY, f32::NEG_INFINITY);
    for &v in значения {
        if v < lo {
            lo = v;
        }
        if v > hi {
            hi = v;
        }
    }
    if !lo.is_finite() || !hi.is_finite() || (hi - lo).abs() < f32::EPSILON {
        return vec![0.0; значения.len()];
    }
    значения.iter().map(|v| (v - lo) / (hi - lo)).collect()
}

/// Свести кандидатов в один ранжированный список.
///
/// Дубликаты по (kind, name) склеиваются: одна сущность, найденная двумя
/// путями (точным совпадением и семантикой), — это ОДНА строка с двумя
/// сработавшими сигналами, а не две строки. Прежнее устройство выдавало
/// её дважды в разных разделах, и агент считал это двумя находками.
pub fn rank(mut кандидаты: Vec<Candidate>, limit: usize) -> Vec<Ranked> {
    if кандидаты.is_empty() {
        return Vec::new();
    }

    // Склейка дубликатов: берём максимум по каждому сигналу.
    let mut индекс: HashMap<(String, String), usize> = HashMap::new();
    let mut слитые: Vec<Candidate> = Vec::with_capacity(кандидаты.len());
    for c in кандидаты.drain(..) {
        let ключ = (c.kind.clone(), c.name.to_lowercase());
        match индекс.get(&ключ) {
            Some(&i) => {
                let s = &mut слитые[i].signals;
                s.exact = s.exact.max(c.signals.exact);
                s.bm25 = s.bm25.max(c.signals.bm25);
                s.semantic = s.semantic.max(c.signals.semantic);
                s.degree = s.degree.max(c.signals.degree);
                s.synonym = s.synonym.max(c.signals.synonym);
                s.idf = s.idf.max(c.signals.idf);
                s.usage = s.usage.max(c.signals.usage);
                if слитые[i].payload.is_empty() {
                    слитые[i].payload = c.payload;
                }
            }
            None => {
                индекс.insert(ключ, слитые.len());
                слитые.push(c);
            }
        }
    }

    let exact: Vec<f32> = слитые.iter().map(|c| c.signals.exact).collect();
    let bm25: Vec<f32> = слитые.iter().map(|c| c.signals.bm25).collect();
    let sem: Vec<f32> = слитые.iter().map(|c| c.signals.semantic).collect();
    let deg: Vec<f32> = слитые.iter().map(|c| c.signals.degree).collect();
    let syn: Vec<f32> = слитые.iter().map(|c| c.signals.synonym).collect();
    let idf: Vec<f32> = слитые.iter().map(|c| c.signals.idf).collect();
    let usg: Vec<f32> = слитые.iter().map(|c| c.signals.usage).collect();

    let (ne, nb, ns, nd) = (
        нормировать(&exact),
        нормировать(&bm25),
        нормировать(&sem),
        нормировать(&deg),
    );
    let (nsy, ni, nu) = (нормировать(&syn), нормировать(&idf), нормировать(&usg));

    let mut out: Vec<Ranked> = слитые
        .into_iter()
        .enumerate()
        .map(|(i, c)| {
            let вклад = [
                (ne[i] * W_EXACT, "имя"),
                (nsy[i] * W_SYNONYM, "синоним"),
                (nb[i] * W_BM25, "текст"),
                (ns[i] * W_SEMANTIC, "смысл"),
                (ni[i] * W_IDF, "редкость"),
                (nu[i] * W_USAGE, "использование"),
                (nd[i] * W_DEGREE, "связность"),
            ];
            let score = вклад.iter().map(|(v, _)| v).sum::<f32>();
            let reason = вклад
                .iter()
                .max_by(|a, b| a.0.partial_cmp(&b.0).unwrap_or(std::cmp::Ordering::Equal))
                .map(|(_, r)| *r)
                .unwrap_or("—");
            Ranked {
                kind: c.kind,
                name: c.name,
                payload: c.payload,
                score,
                signals: c.signals,
                reason,
            }
        })
        .collect();

    out.sort_by(|a, b| {
        b.score
            .partial_cmp(&a.score)
            .unwrap_or(std::cmp::Ordering::Equal)
            // При равном балле — короткое имя вперёд: `Контрагенты` полезнее
            // `КонтрагентыФормаСпискаПриИзменении` на общем запросе.
            .then_with(|| a.name.len().cmp(&b.name.len()))
    });
    out.truncate(limit);
    out
}

/// Точность совпадения имени как сигнал.
pub fn точность(имя: &str, запрос: &str) -> f32 {
    let (и, з) = (имя.to_lowercase(), запрос.to_lowercase());
    if и == з {
        1.0
    } else if и.starts_with(&з) {
        0.5
    } else if и.contains(&з) {
        0.25
    } else {
        0.0
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn кандидат(имя: &str, s: Signals) -> Candidate {
        Candidate {
            kind: "method".into(),
            name: имя.into(),
            payload: vec![],
            signals: s,
        }
    }

    #[test]
    fn точное_совпадение_вперёд_семантики() {
        // Жалоба, с которой начался Р-017: искали известное имя, а вперёд
        // лезло «похожее по смыслу».
        let r = rank(
            vec![
                кандидат(
                    "ПохожееПоСмыслу",
                    Signals {
                        semantic: 0.99,
                        ..Default::default()
                    },
                ),
                кандидат(
                    "ЗаказКлиента",
                    Signals {
                        exact: 1.0,
                        semantic: 0.30,
                        ..Default::default()
                    },
                ),
            ],
            10,
        );
        assert_eq!(r[0].name, "ЗаказКлиента");
        assert_eq!(r[0].reason, "имя");
    }

    #[test]
    fn одинаковый_сигнал_не_решает() {
        // Урок 10.08: сигнал с нулевым разбросом не должен влиять на порядок.
        let одинаковая_семантика = 0.7;
        let r = rank(
            vec![
                кандидат(
                    "А",
                    Signals {
                        exact: 0.25,
                        semantic: одинаковая_семантика,
                        ..Default::default()
                    },
                ),
                кандидат(
                    "Б",
                    Signals {
                        exact: 1.0,
                        semantic: одинаковая_семантика,
                        ..Default::default()
                    },
                ),
            ],
            10,
        );
        assert_eq!(r[0].name, "Б");
    }

    #[test]
    fn дубликат_склеивается_в_одну_строку() {
        // Одна сущность, найденная двумя путями, — одна находка, а не две.
        let r = rank(
            vec![
                кандидат(
                    "Контрагенты",
                    Signals {
                        exact: 1.0,
                        ..Default::default()
                    },
                ),
                кандидат(
                    "контрагенты",
                    Signals {
                        semantic: 0.9,
                        ..Default::default()
                    },
                ),
            ],
            10,
        );
        assert_eq!(r.len(), 1);
        assert_eq!(r[0].signals.exact, 1.0);
        assert_eq!(r[0].signals.semantic, 0.9);
    }

    #[test]
    fn нормировка_вырожденного_даёт_ноль() {
        assert_eq!(нормировать(&[0.5, 0.5, 0.5]), vec![0.0, 0.0, 0.0]);
    }

    #[test]
    fn сырые_сигналы_переживают_нормировку() {
        // После нормировки «лучший из мусора» равен единице. Отличить его
        // от точного попадания можно только по сырому значению.
        let r = rank(
            vec![
                кандидат(
                    "Мусор1",
                    Signals {
                        semantic: 0.51,
                        ..Default::default()
                    },
                ),
                кандидат(
                    "Мусор2",
                    Signals {
                        semantic: 0.54,
                        ..Default::default()
                    },
                ),
            ],
            10,
        );
        assert_eq!(r[0].score, W_SEMANTIC); // нормированная единица
        assert!(r[0].signals.semantic < 0.6); // а сырое значение — мусор
    }

    #[test]
    fn точность_различает_три_степени() {
        assert_eq!(точность("ЗаказКлиента", "заказклиента"), 1.0);
        assert_eq!(точность("ЗаказКлиентаФорма", "ЗаказКлиента"), 0.5);
        assert_eq!(точность("ПроведениеЗаказКлиента", "ЗаказКлиента"), 0.25);
        assert_eq!(точность("Контрагенты", "ЗаказКлиента"), 0.0);
    }
}
