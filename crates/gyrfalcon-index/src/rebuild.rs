//! Полная пересборка поверх живого индекса.
//!
//! # Задача
//!
//! `gyrfalcon build <src> --out <живой>.db` под работающим сервером должен
//! закончиться новым индексом на прежнем месте — без остановки сервера.
//!
//! # Почему не просто «перезаписать»
//!
//! На Windows файл, открытый SQLite, нельзя ни удалить, ни переименовать, ни
//! подменить другим (замер 13.11.2026: `WinError 5` / `WinError 32`, после
//! закрытия соединения подмена проходит). Сервер держит пул соединений всё
//! время жизни процесса, поэтому файл должен отпустить сам сервер, а сборка
//! может только попросить. Прежняя сборка удаляла старый файл с
//! `let _ = remove_file(out)`: на занятом файле удаление молча не проходило,
//! и сборка открывала тот же старый файл.
//!
//! # Как устроено
//!
//! 1. Сборка ставит рядом метку `<индекс>.building` и обновляет в ней пульс,
//!    пока жива ([`Метка`]).
//! 2. Пишет новый индекс в `<индекс>.new` — живой файл не трогается.
//! 3. Сервер, увидев живую метку, закрывает соединения с индексом и на вызовы
//!    отвечает отказом «идёт полная пересборка» (решение 16.10.2026: во время
//!    пересборки индекс не отдаётся вовсе — его пересобирают как раз потому,
//!    что старый неполон).
//! 4. Сборка подменяет файл одним `rename`, повторяя попытку, пока сервер не
//!    отпустит файл ([`подменить`]). Не вышло — ошибка сборки, живой индекс цел.
//! 5. Метка снимается. Сервер замечает новый файл по отпечатку и открывает
//!    проект заново.
//!
//! # Почему пульс, а не pid
//!
//! Метка оборванной сборки (убили процесс, выключили машину) не должна
//! закрыть проект навсегда. Проверка «жив ли pid» на каждой платформе своя и
//! врёт при повторном использовании номера; пульс от времени не зависит от
//! платформы: метка, которую давно не обновляли, — мёртвая. pid пишется для
//! человека, читающего отказ.

use std::path::{Path, PathBuf};
use std::sync::mpsc;
use std::time::{Duration, SystemTime, UNIX_EPOCH};

use serde::{Deserialize, Serialize};

/// Как часто сборка обновляет пульс метки.
pub const ПУЛЬС: Duration = Duration::from_secs(2);

/// Метка без пульса дольше этого — мёртвая (оборванная сборка).
///
/// С запасом против пульса: сборка нагружает все ядра, и поток пульса может
/// опоздать на секунды. Ложная «смерть» живой сборки стоила бы того, что
/// сервер снова откроет старый файл и подмена будет ждать.
pub const ЖИВА_СЕКУНД: u64 = 20;

/// Сколько сборка ждёт, пока сервер отпустит файл.
///
/// Сервер опрашивает метки раз в полсекунды и отпускает файл, дождавшись
/// идущих вызовов. Долгий вызов идёт минуту и больше (`grep` без `module` на
/// 30 тыс. модулей), а потерять из-за него готовую сборку обиднее, чем
/// подождать: новых вызовов сервер в это время уже не принимает. Цена запаса —
/// сервер, не знающий меток, держит сборку до отказа эти же пять минут.
pub const ЖДАТЬ_ПОДМЕНЫ: Duration = Duration::from_secs(300);

/// Содержимое метки.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct СостояниеМетки {
    /// Процесс сборки — для человека, не для проверки жизни.
    pub pid: u32,
    /// Начало сборки, секунды эпохи.
    pub started: u64,
    /// Последний пульс, секунды эпохи.
    pub beat: u64,
    /// Сколько шла прошлая сборка этого индекса, мс. `None` — неизвестно
    /// (индекса не было или он собран до появления `build_ms`).
    pub expected_ms: Option<u64>,
}

fn сейчас() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0)
}

fn с_суффиксом(индекс: &Path, суффикс: &str) -> PathBuf {
    let mut s = индекс.as_os_str().to_os_string();
    s.push(суффикс);
    PathBuf::from(s)
}

/// Путь метки пересборки индекса.
pub fn путь_метки(индекс: &Path) -> PathBuf {
    с_суффиксом(индекс, ".building")
}

/// Путь, куда пишется новый индекс до подмены.
///
/// Расширение не `.db` намеренно: реестр проектов берёт только `*.db`, и
/// недособранный файл проектом не станет.
pub fn путь_сборки(индекс: &Path) -> PathBuf {
    с_суффиксом(индекс, ".new")
}

/// Живая метка пересборки индекса, если она есть.
///
/// Метку, которую сейчас дописывают, можно прочитать пустой или обрезанной.
/// Такая не выдаётся за отсутствие пересборки: жизнь тогда судится по
/// времени изменения файла.
///
/// Разница с пульсом берётся по модулю: пульс «из будущего» (часы перевели
/// назад) иначе держал бы мёртвую метку живой, пока часы его не догонят.
pub fn живая(индекс: &Path) -> Option<СостояниеМетки> {
    let путь = путь_метки(индекс);
    let текст = std::fs::read_to_string(&путь).ok();
    let now = сейчас();
    if let Some(м) = текст
        .as_deref()
        .and_then(|t| serde_json::from_str::<СостояниеМетки>(t).ok())
    {
        return (now.abs_diff(м.beat) <= ЖИВА_СЕКУНД).then_some(м);
    }
    let изменена = std::fs::metadata(&путь)
        .and_then(|m| m.modified())
        .ok()?
        .duration_since(UNIX_EPOCH)
        .ok()?
        .as_secs();
    (now.abs_diff(изменена) <= ЖИВА_СЕКУНД).then_some(СостояниеМетки {
        pid: 0,
        started: изменена,
        beat: изменена,
        expected_ms: None,
    })
}

/// Текст отказа для вызова, пришедшего во время пересборки.
pub fn отказ(индекс: &Path, м: &СостояниеМетки) -> String {
    let идёт = сейчас().saturating_sub(м.started);
    let ожидание = match м.expected_ms {
        Some(ms) => {
            let всего = ms.div_ceil(1000);
            match всего.checked_sub(идёт) {
                Some(осталось) if осталось > 0 => {
                    format!("; прошлая сборка шла {всего} с — ждать ещё около {осталось} с")
                }
                _ => format!("; прошлая сборка шла {всего} с — уже дольше, ждать недолго"),
            }
        }
        None => "; длительность прошлой сборки неизвестна".into(),
    };
    let pid = if м.pid == 0 {
        String::new()
    } else {
        format!(", pid {}", м.pid)
    };
    format!(
        "индекс {} сейчас полностью пересобирается (идёт {идёт} с{pid}){ожидание}. \
         Старый индекс на это время не отдаётся: его пересобирают, потому что он \
         неполон. Повторите вызов после окончания сборки",
        индекс.display()
    )
}

/// Метка пересборки: стоит, пока жив этот объект, и снимается в `Drop` —
/// в том числе при ошибке сборки.
pub struct Метка {
    путь: PathBuf,
    стоп: Option<mpsc::Sender<()>>,
    поток: Option<std::thread::JoinHandle<()>>,
}

impl Метка {
    /// Поставить метку. Отказ, если уже идёт другая сборка этого индекса:
    /// две сборки подменяли бы файл друг у друга.
    ///
    /// Метка создаётся `create_new` — атомарно на уровне файловой системы.
    /// «Проверить, потом записать» пропускало бы две сборки, запущенные
    /// одновременно: обе увидели бы, что метки нет.
    pub fn поставить(
        индекс: &Path, expected_ms: Option<u64>
    ) -> std::io::Result<Self> {
        let путь = путь_метки(индекс);
        let started = сейчас();
        let состояние = СостояниеМетки {
            pid: std::process::id(),
            started,
            beat: started,
            expected_ms,
        };
        let текст = serde_json::to_string(&состояние).map_err(std::io::Error::other)?;
        let создать = || {
            std::fs::OpenOptions::new()
                .write(true)
                .create_new(true)
                .open(&путь)
                .and_then(|mut f| std::io::Write::write_all(&mut f, текст.as_bytes()))
        };
        match создать() {
            Ok(()) => {}
            Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {
                if let Some(м) = живая(индекс) {
                    return Err(std::io::Error::new(
                        std::io::ErrorKind::AlreadyExists,
                        format!(
                            "индекс {} уже пересобирается другим процессом (pid {}, начата {} с назад); \
                             если та сборка оборвана, метка {} перестанет считаться живой через {} с",
                            индекс.display(),
                            м.pid,
                            сейчас().saturating_sub(м.started),
                            путь.display(),
                            ЖИВА_СЕКУНД
                        ),
                    ));
                }
                // Метка оборванной сборки: убрать и занять место. Удалить её
                // одновременно могут двое — второй получит «нет файла», это
                // не ошибка; занять место после этого сможет только один.
                match std::fs::remove_file(&путь) {
                    Ok(()) => {}
                    Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
                    Err(e) => return Err(e),
                }
                создать()?;
            }
            Err(e) => return Err(e),
        }

        let (стоп, сигнал) = mpsc::channel::<()>();
        let путь_потока = путь.clone();
        let поток = std::thread::Builder::new()
            .name("gyrfalcon-build-beat".into())
            .spawn(move || {
                let mut текущее = состояние;
                // `recv_timeout` и есть сон до следующего пульса: сигнал стопа
                // (или отпавший отправитель) будит сразу.
                while let Err(mpsc::RecvTimeoutError::Timeout) = сигнал.recv_timeout(ПУЛЬС)
                {
                    текущее.beat = сейчас();
                    let _ = записать(&путь_потока, &текущее);
                }
            })?;
        Ok(Self {
            путь,
            стоп: Some(стоп),
            поток: Some(поток),
        })
    }
}

impl Drop for Метка {
    fn drop(&mut self) {
        drop(self.стоп.take());
        if let Some(п) = self.поток.take() {
            let _ = п.join();
        }
        let _ = std::fs::remove_file(&self.путь);
    }
}

fn записать(
    путь: &Path, метка: &СостояниеМетки
) -> std::io::Result<()> {
    let текст = serde_json::to_string(метка).map_err(std::io::Error::other)?;
    std::fs::write(путь, текст)
}

/// Подменить живой индекс собранным, дожидаясь, пока его отпустят.
///
/// Каждая попытка — один `rename` поверх: на Windows это `MoveFileEx` с
/// заменой, на Unix — атомарная подмена. Между попытками сервер, увидевший
/// метку, закрывает соединения.
pub fn подменить(
    собранный: &Path, индекс: &Path, ждать: Duration
) -> std::io::Result<()> {
    let до = std::time::Instant::now() + ждать;
    loop {
        match std::fs::rename(собранный, индекс) {
            Ok(()) => return Ok(()),
            Err(e) if std::time::Instant::now() >= до => {
                return Err(std::io::Error::new(
                    e.kind(),
                    format!(
                        "не удалось подменить {} за {} с: {e}. Файл держит другой процесс — \
                         сервер gyrfalcon без пересборки на месте (0.1.24 и раньше), \
                         просмотрщик SQLite или вторая сборка. Новый индекс собран и лежит в {}: \
                         освободите файл и переименуйте его вручную или повторите сборку",
                        индекс.display(),
                        ждать.as_secs(),
                        собранный.display()
                    ),
                ));
            }
            Err(_) => std::thread::sleep(Duration::from_millis(100)),
        }
    }
}

/// Длительность прошлой сборки индекса, если она записана.
pub fn прошлая_длительность(индекс: &Path) -> Option<u64> {
    if !индекс.is_file() {
        return None;
    }
    let c =
        rusqlite::Connection::open_with_flags(индекс, rusqlite::OpenFlags::SQLITE_OPEN_READ_ONLY)
            .ok()?;
    c.query_row(
        "SELECT value FROM index_meta WHERE key = 'build_ms'",
        [],
        |r| r.get::<_, String>(0),
    )
    .ok()?
    .parse()
    .ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn каталог(метка: &str) -> PathBuf {
        let d =
            std::env::temp_dir().join(format!("gyrfalcon-rebuild-{метка}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        d
    }

    #[test]
    fn метка_живёт_пока_жив_объект_и_снимается_в_drop() {
        let d = каталог("drop");
        let и = d.join("x.db");
        {
            let _м = Метка::поставить(&и, Some(5000)).unwrap();
            let м = живая(&и).expect("метка живая");
            assert_eq!(м.pid, std::process::id());
            assert_eq!(м.expected_ms, Some(5000));
        }
        assert!(!путь_метки(&и).exists(), "метка снята");
        assert!(живая(&и).is_none());
        let _ = std::fs::remove_dir_all(d);
    }

    #[test]
    fn вторая_сборка_того_же_индекса_отказывает() {
        let d = каталог("twice");
        let и = d.join("x.db");
        let _м = Метка::поставить(&и, None).unwrap();
        let e = Метка::поставить(&и, None).err().expect("отказ");
        assert!(e.to_string().contains("уже пересобирается"), "{e}");
        let _ = std::fs::remove_dir_all(d);
    }

    #[test]
    fn метка_без_пульса_мёртвая() {
        let d = каталог("dead");
        let и = d.join("x.db");
        let давно = сейчас() - ЖИВА_СЕКУНД - 5;
        записать(
            &путь_метки(&и),
            &СостояниеМетки {
                pid: 1,
                started: давно,
                beat: давно,
                expected_ms: None,
            },
        )
        .unwrap();
        assert!(живая(&и).is_none(), "оборванная сборка не закрывает проект");
        // Пульс «из будущего» (часы перевели назад) — тоже мёртвая метка.
        let потом = сейчас() + 3600;
        записать(
            &путь_метки(&и),
            &СостояниеМетки {
                pid: 1,
                started: потом,
                beat: потом,
                expected_ms: None,
            },
        )
        .unwrap();
        assert!(живая(&и).is_none(), "пульс из будущего не держит метку");
        // И не мешает новой сборке.
        let _м = Метка::поставить(&и, None).unwrap();
        assert!(живая(&и).is_some());
        let _ = std::fs::remove_dir_all(d);
    }

    #[test]
    fn обрезанная_метка_судится_по_времени_файла() {
        let d = каталог("torn");
        let и = d.join("x.db");
        std::fs::write(путь_метки(&и), "{\"pid\":").unwrap();
        assert!(живая(&и).is_some(), "свежая недописанная метка — живая");
        let _ = std::fs::remove_dir_all(d);
    }

    #[test]
    fn подмена_ждёт_освобождения_файла() {
        let d = каталог("swap");
        let и = d.join("x.db");
        let н = путь_сборки(&и);
        std::fs::write(&и, "старый").unwrap();
        std::fs::write(&н, "новый").unwrap();
        подменить(&н, &и, Duration::from_secs(5)).unwrap();
        assert_eq!(std::fs::read_to_string(&и).unwrap(), "новый");
        assert!(!н.exists());
        let _ = std::fs::remove_dir_all(d);
    }

    #[test]
    fn отказ_называет_причину_и_ожидание() {
        let м = СостояниеМетки {
            pid: 42,
            started: сейчас() - 10,
            beat: сейчас(),
            expected_ms: Some(100_000),
        };
        let т = отказ(Path::new("ut.db"), &м);
        assert!(т.contains("пересобирается"), "{т}");
        assert!(т.contains("pid 42"), "{т}");
        assert!(т.contains("ждать ещё около"), "{т}");
    }
}
