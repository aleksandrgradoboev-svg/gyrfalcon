//! Разбивка имён 1С на токены.
//!
//! # Зачем отдельный модуль
//!
//! Семантический поиск работает не по именам целиком, а по их частям:
//! `ПроведениеДокументаЗаказКлиента` — это `проведение`, `документа`, `заказ`,
//! `клиента`. Без разбивки поиск остаётся лексическим и находит только точное
//! вхождение подстроки — ровно то, что умеет FTS5 и без нас.
//!
//! # Чего здесь нет и не будет
//!
//! Прежний инструмент (`прежний инструмент`) токенизации не имеет вовсе: у него полнотекстовый
//! поиск по именам через FTS5. Поэтому здесь **нечего переносить** и не с чем
//! сверяться поимённо — в отличие от 27 таблиц метаданных. Это новый код,
//! и его правильность доказывается тестами на разобранных случаях, а не
//! паритетом с чужим индексом.
//!
//! # Главная частность: кириллица
//!
//! Готовые разбиватели CamelCase пишутся под латиницу и на `ЗаказКлиента`
//! либо молчат, либо режут по байтам посреди символа (кириллица в UTF-8
//! двухбайтовая). Отсюда весь разбор идёт по `char`, а регистр определяется
//! методами Unicode, а не сравнением с диапазоном `A..Z`.

/// Минимальная длина токена, попадающего в выдачу.
///
/// Односимвольные обрывки (`и`, `в`, `X`) не несут смысла, но раздувают
/// словарь и портят IDF: они встречаются всюду и потому весят почти ноль.
const MIN_TOKEN_LEN: usize = 2;

/// Разбить имя на токены нижнего регистра.
///
/// Правила границы, все — на разобранных случаях (см. тесты):
///
/// * смена регистра `строчная → ПРОПИСНАЯ`: `ЗаказКлиента` → `заказ`, `клиента`;
/// * конец аббревиатуры перед словом: `НДСПродажи` → `ндс`, `продажи`
///   (граница ставится перед ПОСЛЕДНЕЙ прописной серии, а не после);
/// * смена алфавита: `HTTPСервис` → `http`, `сервис`;
/// * цифры отделяются от букв: `НДС18` → `ндс`, `18`;
/// * разделители `_ . - / \ ( ) , ;` и пробелы режут всегда.
///
/// Возвращает токены **в порядке появления**, с повторами: частота считается
/// выше по стеку, и решать за неё здесь нельзя.
pub fn tokenize(name: &str) -> Vec<String> {
    let chars: Vec<char> = name.chars().collect();
    let mut out = Vec::new();
    let mut cur = String::new();

    for i in 0..chars.len() {
        let c = chars[i];

        if is_separator(c) {
            push_token(&mut out, &mut cur);
            continue;
        }

        if !cur.is_empty() && is_boundary(&chars, i) {
            push_token(&mut out, &mut cur);
        }

        cur.push(c);
    }
    push_token(&mut out, &mut cur);
    out
}

/// Разделитель: всё, что не буква и не цифра.
fn is_separator(c: char) -> bool {
    !c.is_alphanumeric()
}

/// Стоит ли граница токена ПЕРЕД символом `i`.
///
/// Смотрит на соседей, а не только на текущий символ: граница аббревиатуры
/// (`НДСПродажи`) видна лишь по тому, что за прописной идёт строчная.
fn is_boundary(chars: &[char], i: usize) -> bool {
    let prev = chars[i - 1];
    let c = chars[i];

    // Цифра рядом с буквой: НДС18 → ндс, 18.
    if c.is_numeric() != prev.is_numeric() {
        return true;
    }

    // Смена алфавита: HTTPСервис → http, сервис.
    if c.is_alphabetic() && prev.is_alphabetic() && is_cyrillic(c) != is_cyrillic(prev) {
        return true;
    }

    // строчная → ПРОПИСНАЯ: ЗаказКлиента → заказ, клиента.
    if c.is_uppercase() && prev.is_lowercase() {
        return true;
    }

    // Хвост аббревиатуры: НДСПродажи → ндс, продажи.
    // Граница ставится перед ПРЕДПОСЛЕДНЕЙ прописной, потому что последняя
    // прописная принадлежит уже следующему слову ("П" от "Продажи").
    if c.is_uppercase() && prev.is_uppercase() {
        if let Some(&next) = chars.get(i + 1) {
            if next.is_lowercase() {
                return true;
            }
        }
    }

    false
}

/// Положить накопленный токен, если он достаточно длинный.
fn push_token(out: &mut Vec<String>, cur: &mut String) {
    if cur.chars().count() >= MIN_TOKEN_LEN {
        out.push(cur.to_lowercase());
    }
    cur.clear();
}

/// Кириллический ли символ.
///
/// Проверка по диапазону, а не по `is_alphabetic`: нужен именно алфавит,
/// чтобы поймать границу `HTTPСервис`, где обе стороны — буквы.
fn is_cyrillic(c: char) -> bool {
    matches!(c, '\u{0400}'..='\u{04FF}' | '\u{0500}'..='\u{052F}')
}

#[cfg(test)]
mod tests {
    use super::*;

    fn t(s: &str) -> Vec<String> {
        tokenize(s)
    }

    #[test]
    fn кириллический_camelcase() {
        assert_eq!(t("ЗаказКлиента"), vec!["заказ", "клиента"]);
        assert_eq!(
            t("ПроведениеДокументаЗаказКлиента"),
            vec!["проведение", "документа", "заказ", "клиента"]
        );
    }

    #[test]
    fn аббревиатура_перед_словом() {
        // Граница ПЕРЕД последней прописной, а не после серии.
        assert_eq!(t("НДСПродажи"), vec!["ндс", "продажи"]);
        assert_eq!(
            t("УстановитьНДСПродажи"),
            vec!["установить", "ндс", "продажи"]
        );
    }

    #[test]
    fn аббревиатура_целиком() {
        // Не разваливать на буквы, когда за серией ничего нет.
        assert_eq!(t("НДС"), vec!["ндс"]);
        assert_eq!(t("УстановитьНДС"), vec!["установить", "ндс"]);
    }

    #[test]
    fn смена_алфавита() {
        assert_eq!(t("HTTPСервис"), vec!["http", "сервис"]);
        assert_eq!(t("ОбменWSСервис"), vec!["обмен", "ws", "сервис"]);
    }

    #[test]
    fn цифры_отделяются() {
        assert_eq!(t("НДС18"), vec!["ндс", "18"]);
        assert_eq!(t("НДСРеализация0"), vec!["ндс", "реализация"]);
    }

    #[test]
    fn разделители() {
        assert_eq!(
            t("ОбщийМодуль.МойМетод"),
            vec!["общий", "модуль", "мой", "метод"]
        );
        assert_eq!(t("Заказ_Клиента"), vec!["заказ", "клиента"]);
        assert_eq!(t("Catalogs/Номенклатура"), vec!["catalogs", "номенклатура"]);
    }

    #[test]
    fn односимвольные_отбрасываются() {
        // "0" из НДСРеализация0 и одиночная буква в словарь не идут.
        assert_eq!(t("СтрокаX"), vec!["строка"]);
        assert!(t("X").is_empty());
    }

    #[test]
    fn пустое_и_мусор() {
        assert!(t("").is_empty());
        assert!(t("___").is_empty());
        assert!(t("...").is_empty());
    }

    #[test]
    fn латиница_как_у_всех() {
        assert_eq!(t("GetUserName"), vec!["get", "user", "name"]);
        assert_eq!(t("parseXMLDocument"), vec!["parse", "xml", "document"]);
    }

    #[test]
    fn ё_не_ломает_границу() {
        // Форк грамматики чинил ё/Ё в идентификаторах — здесь она обязана
        // быть обычной буквой, а не разделителем.
        assert_eq!(t("УчётЗатрат"), vec!["учёт", "затрат"]);
        assert_eq!(t("ПолныйУчёт"), vec!["полный", "учёт"]);
    }

    #[test]
    fn повторы_сохраняются() {
        // Частоту считает вызывающий; здесь дедупа нет.
        assert_eq!(t("ЗаказЗаказ"), vec!["заказ", "заказ"]);
    }
}
