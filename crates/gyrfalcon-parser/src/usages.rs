//! Упоминания объектов метаданных в коде — сырьё таблицы `metadata_code_usages`.
//!
//! Три вида, различаемые прежний инструментом и воспроизведённые здесь. Правила выведены
//! **замером на живом корпусе** 28.08.2026, а не из общего знания о 1С: для
//! каждой из 259 401 строки прежнего инструмента прочитан настоящий текст этой строки и
//! выяснено, какая конструкция за ней стоит. Правила ниже объясняют 99,97%
//! (259 316 из 259 401); необъяснённый остаток разобран и оказался ложными
//! срабатываниями прежнего инструмента, а не пробелом в правилах.
//!
//! | Вид | Конструкция | Пример |
//! |---|---|---|
//! | `manager` | обращение к менеджеру в КОДЕ | `ПланыСчетов.Хозрасчетный.НДС` |
//! | `query` | литерал `<Единственное>.<Имя>` | `"Справочник.ПрочиеДоходы.Курсовые"`, текст запроса |
//! | `ref_type` | литерал `<Единственное><Суффикс>.<Имя>` | `Тип("ДокументСсылка.ОперацияБух")` |
//!
//! # Почему `ref_type` — про литерал, а не про `Тип(...)`
//!
//! Замер: из 17 336 строк `ref_type` прежнего инструмента только 11 665 стоят внутри
//! `Тип("…")`. Остальные 5 671 — `Новый ОписаниеТипов("СправочникСсылка.Х")`
//! и родня. То есть распознаётся сам литерал, а окружающая функция не важна.
//! Правило от этого стало проще, а не сложнее.
//!
//! # Русские имена видов взяты из фактов, а не из памяти
//!
//! Соответствие `Справочники` → `Catalog` выведено обратным замером: для строк
//! прежнего инструмента прочитан исходный текст и посчитано, какое русское слово стоит перед
//! именем объекта. Отсюда же три семейства форм — множественная, единственная
//! и единственная с суффиксом — и закрытый список суффиксов.

use tree_sitter::Node;

/// Вид упоминания. Значения — прежний инструментские, чтобы сверка шла без перевода.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum UsageKind {
    /// Обращение к менеджеру в коде: `Справочники.Номенклатура`.
    Manager,
    /// Полное имя в строковом литерале: тексты запросов, `ПредопределенныйЭлемент`.
    Query,
    /// Ссылочный тип в литерале: `ДокументСсылка.Х`, `СправочникОбъект.Х`.
    RefType,
}

impl UsageKind {
    pub fn as_str(self) -> &'static str {
        match self {
            UsageKind::Manager => "manager",
            UsageKind::Query => "query",
            UsageKind::RefType => "ref_type",
        }
    }
}

/// Упоминание объекта метаданных в точке употребления.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MetadataUsage {
    /// Английская форма: `Document.ОперацияБух`.
    pub object_ref: String,
    /// Она же в нижнем регистре — ключ сверки, столбец прежнего инструмента.
    pub object_ref_key: String,
    /// Что стоит после имени объекта: реквизит, предопределённый элемент,
    /// имя формы. `None` — обращение к самому объекту.
    pub member_path: Option<String>,
    pub kind: UsageKind,
    pub line: u32,
}

