# -*- coding: utf-8 -*-
"""Логотип из штрихового рисунка — один файл, живущий в обеих темах GitHub.

# Чего я не понимал шесть попыток подряд (объяснил владелец)

В оригинале за контурной линией идёт БЕЛАЯ БУМАГА — просвет между линией
и штриховкой. Срез через крыло: 244 (фон) → 81 (линия контура) → 255
(бумага) → 165-199 (штриховка нутра).

Заливка силуэта считала эту бумагу «телом» и красила белым — отсюда белая
полоса вдоль всего контура ИЗНУТРИ. Это был не артефакт и не ореол:
я честно переносил белую бумагу оригинала в силуэт.

Правильно — простая ИНВЕРСИЯ: тёмная линия становится светлой, бумага
(и снаружи, и внутри) становится прозрачной. Заливка не нужна вовсе.

# Почему одна картинка, а не две (решение владельца 30.08.2026)

GitHub умеет подставлять разные файлы по `prefers-color-scheme` через
`<picture>`, и это гарантированный путь. Но он требует держать два
изображения синхронными, а рассинхрон замечается не сразу: правишь одно,
второе живёт своей жизнью и вылезает у читателя с другой темой.

Одна картинка работает, если штрих взят СРЕДНЕЙ ЯРКОСТИ. Контраст
считается по формуле WCAG к обоим фонам сразу: тон, дающий 3:1 и к белому
(#ffffff), и к тёмному (#0d1117), читается в любой теме. Такой диапазон
существует и он узкий — примерно L* 55–65, — поэтому подбирается замером,
а не на глаз.

Прозрачность здесь обязательна: залитый фон и есть та причина, по которой
прежний логотип висел тёмным прямоугольником на светлой теме.

Запуск:
    python tools/make-logo.py [делитель] [порог_бумаги]
"""
import sys

from PIL import Image, ImageOps

sys.stdout.reconfigure(encoding="utf-8")

ФАЙЛ = "C:/Users/User/Downloads/фалькон.jpg"
ФАЙЛ_ВЫХОД = "docs/img/falcon.png"
ДЕЛ = int(sys.argv[1]) if len(sys.argv) > 1 else 2
ПОРОГ_БУМАГИ = int(sys.argv[2]) if len(sys.argv) > 2 else 236

# Палитра, читаемая на белом И на тёмном.
#
# Прежняя была рассчитана только на тёмный фон: самая яркая ступень
# (246,250,255) на белом исчезает совсем, самая тусклая (58,86,130) на
# белом превращается в грязь. Здесь все четыре ступени лежат в коридоре,
# где контраст к обоим фонам не ниже 3:1 — проверяется функцией ниже.
#
# Тон синий не случайно: серый в этом коридоре выглядит выцветшим, а синий
# сохраняет характер при той же яркости.
# ТРИ ступени, а не четыре — предел, установленный замером, а не вкусом.
#
# Коридор, где контраст к белому и к #0d1117 одновременно не ниже 3:1,
# узок: примерно от (73,101,151) до (106,147,220). Четыре различимые
# градации в него не влезают — крайние вываливаются на одном из фонов
# (замер: самая светлая давала 2,9 к белому, самая тёмная 2,5 к тёмному).
#
# Полупрозрачность четвёртой ступени тоже проверена и отвергнута: штрих
# с альфой приближается к фону по определению, и тонет в обоих (1,8 и 2,6).
#
# Поэтому градаций три, и самый слабый штрих оригинала уходит в самую
# светлую из них, а не в отдельную четвёртую.
КОНТУР = (60, 96, 155)  # самая тёмная линия оригинала — самая насыщенная тут
ПОЛУТОН = (80, 120, 185)
ПЕСТРИНА = (100, 145, 210)
СВЕТЛЫЙ = ПЕСТРИНА  # слабый штрих сливается с пестриной: своей ступени ему нет

ФОН_ТЁМНЫЙ = (13, 17, 23)  # #0d1117 — тёмная тема GitHub
ФОН_СВЕТЛЫЙ = (255, 255, 255)


def яркость(цвет):
    """Относительная яркость по WCAG 2.1."""

    def канал(c):
        c = c / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = (канал(c) for c in цвет)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def контраст(a, b):
    """Отношение контраста по WCAG: от 1 (нет) до 21 (чёрное на белом)."""
    я1, я2 = sorted((яркость(a), яркость(b)), reverse=True)
    return (я1 + 0.05) / (я2 + 0.05)


def проверить_палитру():
    """Напечатать контраст каждой ступени к обоим фонам.

    Печатается, а не молча проверяется: цифру должен увидеть человек,
    который решает, годится ли логотип. Порог 3:1 — минимум WCAG для
    крупной графики; ниже него штрих на одном из фонов «тонет».
    """
    print("контраст ступеней (порог 3,0 к обоим фонам):")
    беда = False
    for имя, цвет in [
        ("контур", КОНТУР),
        ("полутон", ПОЛУТОН),
        ("пестрина", ПЕСТРИНА),
        ("светлый", СВЕТЛЫЙ),
    ]:
        к_белому = контраст(цвет, ФОН_СВЕТЛЫЙ)
        к_тёмному = контраст(цвет, ФОН_ТЁМНЫЙ)
        плохо = min(к_белому, к_тёмному) < 3.0
        беда = беда or плохо
        метка = " ← НИЖЕ ПОРОГА" if плохо else ""
        print(
            f"  {имя:9} {str(цвет):18} к белому {к_белому:4.1f}  "
            f"к тёмному {к_тёмному:4.1f}{метка}"
        )
    return not беда


им = ImageOps.autocontrast(Image.open(ФАЙЛ).convert("L"), cutoff=1)
нш, нв = им.size[0] // ДЕЛ, им.size[1] // ДЕЛ
px = им.resize((нш, нв), Image.LANCZOS).load()

годится = проверить_палитру()

out = Image.new("RGBA", (нш, нв), (0, 0, 0, 0))
o = out.load()
нарисовано = 0
for y in range(нв):
    for x in range(нш):
        я = px[x, y]
        if я >= ПОРОГ_БУМАГИ:
            continue  # бумага — и снаружи, и внутри — остаётся прозрачной
        # Чем ТЕМНЕЕ штрих в оригинале, тем насыщеннее он здесь.
        if я < 90:
            цв = КОНТУР
        elif я < 150:
            цв = ПОЛУТОН
        elif я < 200:
            цв = ПЕСТРИНА
        else:
            цв = СВЕТЛЫЙ
        o[x, y] = (*цв, 255)
        нарисовано += 1

out.save(ФАЙЛ_ВЫХОД, optimize=True)
print(f"\n{нш}x{нв} · штрихов {нарисовано} ({нарисовано * 100 // (нш * нв)}% площади)")
print(f"сохранено: {ФАЙЛ_ВЫХОД}" + ("" if годится else "  ⚠ палитра не прошла порог"))
